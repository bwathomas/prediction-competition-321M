class _DenseResidual(nn.Module):
    def __init__(self, in_dim: int, hidden: int, dropout: float):
        super().__init__()
        self.norm = nn.LayerNorm(in_dim)
        self.fc1 = nn.Linear(in_dim, hidden)
        self.drop = nn.Dropout(dropout)
        self.fc2 = nn.Linear(hidden, 1)

    def forward(self, x):
        h = F.silu(self.fc1(self.norm(x)))
        h = self.drop(h)
        return self.fc2(h).squeeze(-1)


class _GatedResidual(nn.Module):
    def __init__(self, in_dim: int, hidden: int, dropout: float):
        super().__init__()
        self.norm = nn.LayerNorm(in_dim)
        self.gate = nn.Linear(in_dim, hidden)
        self.up = nn.Linear(in_dim, hidden)
        self.down = nn.Linear(hidden, 1)
        self.drop = nn.Dropout(dropout)

    def forward(self, x):
        x = self.norm(x)
        h = F.silu(self.gate(x)) * self.up(x)
        h = self.drop(h)
        return self.down(h).squeeze(-1)


class _ResidualKFactor(_KFactorBase):
    residual_cls = _DenseResidual

    def __init__(self, cfg: dict):
        super().__init__(cfg)
        in_dim = _residual_input_dim(cfg)
        self.residual = self.residual_cls(
            in_dim=in_dim,
            hidden=cfg["residual_hidden_dim"],
            dropout=cfg.get("dropout", 0.0),
        )
        self.lambda_resid = nn.Parameter(
            torch.tensor(float(cfg.get("lambda_resid_init", 0.1))),
            requires_grad=bool(cfg.get("lambda_resid_trainable", True)),
        )

    def forward(self, s, bc, ie, se=None, pool_feats=None, cluster_ids=None, judge_feats=None, nn_feats=None):
        eta_factor, u_s, v_i, ie_out = self._factor(s, bc, ie)
        beta_bc = self.beta(bc)
        cluster_emb = _cluster_emb_runtime(self.cfg, self.cluster_embedding, cluster_ids)
        x = _residual_features(
            self.cfg, u_s, v_i, ie_out, beta_bc, se, pool_feats, cluster_emb, judge_feats, nn_feats
        )
        return eta_factor + self.lambda_resid * self.residual(x)


