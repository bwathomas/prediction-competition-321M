# LLM-as-judge runtime (Path A: ship a local instruction-tuned LM and run
# it per-call). Loaded once at module scope. The per-call score is cached
# in-process on (subject_hash, item_hash) so the same pair is only scored
# once per round even if the platform asks for it many times.
# ---------------------------------------------------------------------------


def _judge_first_token_id(tokenizer, variant: str) -> int | None:
    ids = tokenizer.encode(variant, add_special_tokens=False)
    if not ids:
        return None
    return int(ids[0])


def _judge_token_ids(tokenizer, variants) -> list[int]:
    seen: dict[int, None] = {}
    for v in variants:
        tid = _judge_first_token_id(tokenizer, v)
        if tid is None:
            continue
        seen.setdefault(tid, None)
    return list(seen.keys())


def _judge_render(
    template: str,
    *,
    benchmark: str,
    condition: str,
    subject_content: str,
    item_content: str,
) -> str:
    """Brace-safe substitution of the four named placeholders into the
    judge prompt template.

    We deliberately avoid ``str.format`` here: the substituted values
    (especially item_content, which routinely contains LaTeX/JSON/code
    snippets with ``{`` / ``}``) would otherwise be interpreted as
    format specs and raise ``KeyError`` / ``IndexError``. The exception
    bubbles up through ``score`` and gets swallowed by the zero-fallback
    in ``_get_judge_features``, silently degrading every brace-bearing
    item to all-zero judge features.
    """
    out = template
    out = out.replace("{benchmark}", str(benchmark))
    out = out.replace("{condition}", str(condition))
    out = out.replace("{subject_content}", str(subject_content))
    out = out.replace("{item_content}", str(item_content))
    return out


def _judge_truncate(
    tokenizer,
    *,
    benchmark: str,
    condition: str,
    subject_content: str,
    item_content: str,
) -> str:
    """Char-based shrink of item / subject content until the rendered prompt
    fits in JUDGE_MAX_PROMPT_TOKENS - JUDGE_SUFFIX_RESERVE_TOKENS."""
    rendered = _judge_render(
        JUDGE_PROMPT_TEMPLATE,
        benchmark=benchmark,
        condition=condition,
        subject_content=subject_content,
        item_content=item_content,
    )
    if JUDGE_MAX_PROMPT_TOKENS <= 0:
        return rendered
    ids = tokenizer.encode(rendered, add_special_tokens=False)
    if len(ids) <= JUDGE_MAX_PROMPT_TOKENS:
        return rendered
    suffix_reserve = max(64, int(JUDGE_SUFFIX_RESERVE_TOKENS))
    budget = max(64, int(JUDGE_MAX_PROMPT_TOKENS) - suffix_reserve)
    it_text, sb_text = item_content, subject_content

    def _try(it_t: str, sb_t: str):
        s = _judge_render(
            JUDGE_PROMPT_TEMPLATE,
            benchmark=benchmark,
            condition=condition,
            subject_content=sb_t,
            item_content=it_t,
        )
        return s, len(tokenizer.encode(s, add_special_tokens=False))

    s, n = _try(it_text, sb_text)
    while n > budget and len(it_text) > 64:
        shrink = max(64, (n - budget) * 4)
        it_text = it_text[: max(64, len(it_text) - shrink)]
        s, n = _try(it_text, sb_text)
    while n > budget and len(sb_text) > 64:
        shrink = max(64, (n - budget) * 4)
        sb_text = sb_text[: max(64, len(sb_text) - shrink)]
        s, n = _try(it_text, sb_text)
    if n > JUDGE_MAX_PROMPT_TOKENS:
        ids = tokenizer.encode(s, add_special_tokens=False)
        ids = ids[: int(JUDGE_MAX_PROMPT_TOKENS) - 8]
        s = tokenizer.decode(ids, skip_special_tokens=False) + "\nAnswer:"
    return s


class _LLMJudgeRuntime:
    """Inline LLM-as-judge for the submission runtime. Loaded once."""

    def __init__(self, model_id: str):
        from transformers import AutoModelForCausalLM, AutoTokenizer

        tok = AutoTokenizer.from_pretrained(
            model_id, cache_dir=_CACHE_DIR, local_files_only=True, use_fast=True
        )
        if tok.padding_side != "right":
            tok.padding_side = "right"
        if tok.pad_token_id is None:
            tok.pad_token = tok.eos_token
        self.tokenizer = tok

        dtype = (
            torch.bfloat16
            if (_DEVICE == "cuda" and torch.cuda.is_bf16_supported() and JUDGE_BF16)
            else torch.float32
        )
        # Fallback chain: ``flash_attention_2`` -> default (no kwarg, lets
        # transformers pick eager). The previous "FA2 -> SDPA -> default"
        # chain triggered an OOM on a 24 GB L4 with both 4B models
        # co-resident at bs=16: SDPA's activation memory is 3-4 GB larger
        # than eager's at seq=512, which is enough to push us over.
        # Reverting to the simple FA2-or-default keeps the fast path when
        # FA2 is installed and lands on the *low*-memory eager path
        # otherwise, matching the slow-but-completing baseline.
        attn_kwargs: dict = {}
        if JUDGE_USE_FLASH_ATTENTION and _DEVICE == "cuda":
            attn_kwargs["attn_implementation"] = "flash_attention_2"
        try:
            self.model = AutoModelForCausalLM.from_pretrained(
                model_id,
                cache_dir=_CACHE_DIR,
                torch_dtype=dtype,
                local_files_only=True,
                **attn_kwargs,
            )
            self.attn_impl = (
                attn_kwargs.get("attn_implementation") or "default"
            )
        except (ImportError, ValueError, RuntimeError, TypeError):
            self.model = AutoModelForCausalLM.from_pretrained(
                model_id,
                cache_dir=_CACHE_DIR,
                torch_dtype=dtype,
                local_files_only=True,
            )
            self.attn_impl = "default"
        self.model.eval().to(_DEVICE)

        self.yes_ids = _judge_token_ids(tok, JUDGE_YES_TOKENS)
        self.no_ids = _judge_token_ids(tok, JUDGE_NO_TOKENS)
        if not self.yes_ids or not self.no_ids:
            raise RuntimeError(
                f"Judge yes/no token resolution failed: yes={self.yes_ids} no={self.no_ids}"
            )
        # In-process score cache keyed by (subject_hash, item_hash). Cleared
        # in predict() when the labeled fingerprint changes (new round).
        self.score_cache: dict[tuple[str, str], np.ndarray] = {}

    def score(self, *, benchmark: str, condition: str, subject_content: str, item_content: str) -> np.ndarray:
        prompt = _judge_truncate(
            self.tokenizer,
            benchmark=benchmark,
            condition=condition,
            subject_content=subject_content,
            item_content=item_content,
        )
        enc = self.tokenizer(
            [prompt],
            padding="longest",
            truncation=True,
            max_length=JUDGE_MAX_PROMPT_TOKENS,
            return_tensors="pt",
        )
        input_ids = enc["input_ids"].to(_DEVICE)
        attn = enc["attention_mask"].to(_DEVICE)
        with torch.inference_mode():
            out = self.model(input_ids=input_ids, attention_mask=attn)
        logits = out.logits
        seq_lens = attn.sum(dim=1) - 1
        seq_lens = seq_lens.clamp(min=0)
        next_logits = logits[torch.arange(logits.size(0), device=logits.device), seq_lens]
        logprobs = torch.log_softmax(next_logits.float(), dim=-1)
        yes_t = torch.tensor(self.yes_ids, dtype=torch.long, device=logprobs.device)
        no_t = torch.tensor(self.no_ids, dtype=torch.long, device=logprobs.device)
        lp_yes = torch.logsumexp(logprobs.index_select(1, yes_t), dim=-1)
        lp_no = torch.logsumexp(logprobs.index_select(1, no_t), dim=-1)
        lp_diff = lp_yes - lp_no
        p_yes = torch.sigmoid(lp_diff)
        return np.asarray(
            [
                float(lp_yes.item()),
                float(lp_no.item()),
                float(lp_diff.item()),
                float(p_yes.item()),
            ],
            dtype=np.float32,
        )

    def score_cached(self, *, benchmark: str, condition: str, subject_content: str, item_content: str) -> np.ndarray:
        key = (
            stable_sha256(subject_content),
            stable_sha256(benchmark, condition, item_content),
        )
        cached = self.score_cache.get(key)
        if cached is not None:
            return cached
        vec = self.score(
            benchmark=benchmark,
            condition=condition,
            subject_content=subject_content,
            item_content=item_content,
        )
        self.score_cache[key] = vec
        return vec

    def score_batch(self, rows: list) -> list:
        """Score many (benchmark, condition, subject_content, item_content) rows.

        Returns one length-4 float32 vector per row, in the same order. Used
        by the runtime's lazy-flush path: ``acquisition_function`` enqueues
        every candidate the platform shows it, then the first ``predict()``
        call drains the queue through this method in chunks of
        ``JUDGE_RUNTIME_BATCH_SIZE``. The handbook (sec. 3.5) explicitly
        recommends this architecture for any non-trivial local judge.
        """
        if not rows:
            return []
        B = max(1, int(JUDGE_RUNTIME_BATCH_SIZE))
        out: list = [None] * len(rows)
        for start in range(0, len(rows), B):
            chunk = rows[start : start + B]
            prompts = [
                _judge_truncate(
                    self.tokenizer,
                    benchmark=str(b),
                    condition=str(c),
                    subject_content=str(s),
                    item_content=str(i),
                )
                for (b, c, s, i) in chunk
            ]
            enc = self.tokenizer(
                prompts,
                padding="longest",
                truncation=True,
                max_length=JUDGE_MAX_PROMPT_TOKENS,
                return_tensors="pt",
            )
            input_ids = enc["input_ids"].to(_DEVICE)
            attn = enc["attention_mask"].to(_DEVICE)
            with torch.inference_mode():
                res = self.model(input_ids=input_ids, attention_mask=attn)
            logits = res.logits
            seq_lens = attn.sum(dim=1) - 1
            seq_lens = seq_lens.clamp(min=0)
            next_logits = logits[
                torch.arange(logits.size(0), device=logits.device), seq_lens
            ]
            logprobs = torch.log_softmax(next_logits.float(), dim=-1)
            yes_t = torch.tensor(self.yes_ids, dtype=torch.long, device=logprobs.device)
            no_t = torch.tensor(self.no_ids, dtype=torch.long, device=logprobs.device)
            lp_yes = torch.logsumexp(logprobs.index_select(1, yes_t), dim=-1)
            lp_no = torch.logsumexp(logprobs.index_select(1, no_t), dim=-1)
            lp_diff = lp_yes - lp_no
            p_yes = torch.sigmoid(lp_diff)
            ly = lp_yes.float().cpu().numpy()
            ln = lp_no.float().cpu().numpy()
            ld = lp_diff.float().cpu().numpy()
            py = p_yes.float().cpu().numpy()
            for j in range(len(chunk)):
                out[start + j] = np.asarray(
                    [float(ly[j]), float(ln[j]), float(ld[j]), float(py[j])],
                    dtype=np.float32,
                )
        return out


