class _ItemParameterMap(nn.Module):
    def __init__(self, item_embed_dim: int, k: int, hidden: int, dropout: float = 0.1):
        super().__init__()
        self.norm = nn.LayerNorm(item_embed_dim)
        self.fc1 = nn.Linear(item_embed_dim, hidden)
        self.drop = nn.Dropout(dropout)
        self.head_factor = nn.Linear(hidden, k)
        self.head_diff = nn.Linear(hidden, 1)

    def forward(self, x: torch.Tensor):
        h = F.silu(self.fc1(self.norm(x)))
        h = self.drop(h)
        return self.head_factor(h), self.head_diff(h).squeeze(-1)


class _KFactorBase(nn.Module):
    def __init__(self, cfg: dict):
        super().__init__()
        self.cfg = cfg
        self.mu = nn.Parameter(torch.zeros(1))
        self.alpha = nn.Embedding(cfg["n_subjects"], 1)
        self.beta = nn.Embedding(cfg["n_benchmark_conditions"], 1)
        self.u = nn.Embedding(cfg["n_subjects"], cfg["k"])
        self.item_map = _ItemParameterMap(
            item_embed_dim=cfg["item_embed_dim"],
            k=cfg["k"],
            hidden=cfg["item_map_hidden_dim"],
            dropout=cfg.get("dropout", 0.0),
        )

    def _factor(self, s, bc, ie):
        u_s = self.u(s)
        alpha_s = self.alpha(s).squeeze(-1)
        beta_bc = self.beta(bc).squeeze(-1)
        v_i, d_i = self.item_map(ie)
        k = max(1, self.cfg["k"])
        interaction = (u_s * v_i).sum(dim=-1) / math.sqrt(k)
        eta = self.mu + alpha_s + beta_bc - d_i + interaction
        return eta, u_s, v_i, ie


class _KFactor(_KFactorBase):
    def forward(self, s, bc, ie, se=None):
        eta, *_ = self._factor(s, bc, ie)
        return eta


def _residual_features(cfg, u_s, v_i, ie, beta_bc, se):
    parts = [u_s, v_i, u_s * v_i, ie, beta_bc]
    if cfg.get("use_subject_text_embedding") and se is not None and se.shape[-1] > 0:
        parts.append(se)
    return torch.cat(parts, dim=-1)


def _residual_input_dim(cfg: dict) -> int:
    base = cfg["k"] * 3 + cfg["item_embed_dim"] + 1
    if cfg.get("use_subject_text_embedding"):
        base += int(cfg.get("subject_embed_dim", 0))
    return base


class _DenseResidual(nn.Module):
    def __init__(self, in_dim: int, hidden: int, dropout: float):
        super().__init__()
        self.norm = nn.LayerNorm(in_dim)
        self.fc1 = nn.Linear(in_dim, hidden)
        self.drop = nn.Dropout(dropout)
        self.fc2 = nn.Linear(hidden, 1)

    def forward(self, x):
        h = F.silu(self.fc1(self.norm(x)))
        h = self.drop(h)
        return self.fc2(h).squeeze(-1)


class _GatedResidual(nn.Module):
    def __init__(self, in_dim: int, hidden: int, dropout: float):
        super().__init__()
        self.norm = nn.LayerNorm(in_dim)
        self.gate = nn.Linear(in_dim, hidden)
        self.up = nn.Linear(in_dim, hidden)
        self.down = nn.Linear(hidden, 1)
        self.drop = nn.Dropout(dropout)

    def forward(self, x):
        x = self.norm(x)
        h = F.silu(self.gate(x)) * self.up(x)
        h = self.drop(h)
        return self.down(h).squeeze(-1)


class _ResidualKFactor(_KFactorBase):
    residual_cls = _DenseResidual

    def __init__(self, cfg: dict):
        super().__init__(cfg)
        in_dim = _residual_input_dim(cfg)
        self.residual = self.residual_cls(
            in_dim=in_dim,
            hidden=cfg["residual_hidden_dim"],
            dropout=cfg.get("dropout", 0.0),
        )
        self.lambda_resid = nn.Parameter(
            torch.tensor(float(cfg.get("lambda_resid_init", 0.1))),
            requires_grad=bool(cfg.get("lambda_resid_trainable", True)),
        )

    def forward(self, s, bc, ie, se=None):
        eta_factor, u_s, v_i, ie_out = self._factor(s, bc, ie)
        beta_bc = self.beta(bc)
        x = _residual_features(self.cfg, u_s, v_i, ie_out, beta_bc, se)
        return eta_factor + self.lambda_resid * self.residual(x)


class _MLPResidual(_ResidualKFactor):
    residual_cls = _DenseResidual


class _GatedMLPResidual(_ResidualKFactor):
    residual_cls = _GatedResidual


_REGISTRY = {
    "kfactor": _KFactor,
    "kfactor_mlp": _MLPResidual,
    "kfactor_gated_mlp": _GatedMLPResidual,
}


# ---------------------------------------------------------------------------
# Calibrator (intercept-only / temperature-intercept / identity)
# ---------------------------------------------------------------------------


def _sigmoid(x: float) -> float:
    if x >= 0:
        z = math.exp(-x)
        return 1.0 / (1.0 + z)
    z = math.exp(x)
    return z / (1.0 + z)


def _logit(p: float) -> float:
    p = min(max(p, EPS), 1.0 - EPS)
    return math.log(p / (1.0 - p))


class _Calibrator:
    """Identity by default; replaced in-place by fit_from_labeled()."""

    def __init__(self, state: dict | None = None):
        self.state: dict = dict(state or {"kind": "identity"})

    def apply(self, p: float) -> float:
        if not math.isfinite(p):
            return DEFAULT_PROB
        kind = self.state.get("kind", "identity")
        if kind == "intercept":
            z = _logit(p) + float(self.state.get("b", 0.0))
            return min(max(_sigmoid(z), EPS), 1.0 - EPS)
        if kind == "temp_intercept":
            T = max(0.1, float(self.state.get("T", 1.0)))
            b = float(self.state.get("b", 0.0))
            z = _logit(p) / T + b
            return min(max(_sigmoid(z), EPS), 1.0 - EPS)
        return min(max(p, EPS), 1.0 - EPS)

    def fit_from_labeled(self, labeled_list: list[dict]) -> None:
        if not labeled_list:
            return
        ps: list[float] = []
        ys: list[float] = []
        for ex in labeled_list:
            try:
                y = float(ex.get("label"))
            except (TypeError, ValueError):
                continue
            p_base = _predict_uncalibrated(
                ex.get("benchmark", ""),
                ex.get("condition", "none"),
                ex.get("subject_content", ""),
                ex.get("item_content", ""),
            )
            if math.isfinite(y) and math.isfinite(p_base):
                ys.append(min(max(y, 0.0), 1.0))
                ps.append(p_base)
        if not ps:
            return
        yb = [1 if v >= 0.5 else 0 for v in ys]
        if sum(yb) == 0 or sum(yb) == len(yb):
            return  # degenerate: identity is safer
        if len(ps) >= 30:
            self.state = _fit_temp_intercept(ps, ys)
        elif len(ps) >= 5:
            self.state = _fit_intercept_only(ps, ys)


def _fit_intercept_only(ps: list[float], ys: list[float]) -> dict:
    z = np.log(np.clip(ps, EPS, 1 - EPS)) - np.log(np.clip([1 - p for p in ps], EPS, 1 - EPS))
    y = np.asarray(ys, dtype=float)
    b = 0.0
    for _ in range(50):
        pred = 1.0 / (1.0 + np.exp(-(z + b)))
        grad = float((pred - y).mean())
        hess = float((pred * (1.0 - pred)).mean()) + 1e-6
        step = grad / hess
        b -= step
        if abs(step) < 1e-6:
            break
    if not math.isfinite(b):
        return {"kind": "identity"}
    return {"kind": "intercept", "b": float(b)}


def _fit_temp_intercept(ps: list[float], ys: list[float]) -> dict:
    z = np.log(np.clip(ps, EPS, 1 - EPS)) - np.log(np.clip([1 - p for p in ps], EPS, 1 - EPS))
    y = np.asarray(ys, dtype=float)
    T, b = 1.0, 0.0
    for _ in range(100):
        zt = z / T + b
        pred = 1.0 / (1.0 + np.exp(-zt))
        err = pred - y
        d_b = float(err.mean())
        d_a = float((err * z).mean())
        h_b = float((pred * (1 - pred)).mean()) + 1e-6
        h_a = float((pred * (1 - pred) * z * z).mean()) + 1e-6
        new_b = b - d_b / h_b
        new_a = (1.0 / T) - d_a / h_a
        new_T = 1.0 / max(0.1, new_a)
        if not (math.isfinite(new_b) and math.isfinite(new_T)):
            return {"kind": "identity"}
        if abs(new_b - b) + abs(new_T - T) < 1e-6:
            T, b = new_T, new_b
            break
        T, b = new_T, new_b
    return {"kind": "temp_intercept", "T": float(T), "b": float(b)}


