class _EnsembleModel(nn.Module):
    """Wraps an ensemble of fold-models from K-fold CV training.

    The bundle layout written by ``export_ensemble_run`` packs M
    configurations -- each with its own ``model_name`` / ``model_cfg`` --
    and per-configuration K trained fold checkpoints. The final
    submission prediction is

        p = sum_c w_c * (mean_k sigmoid(model_{c,k}(x)))

    where ``w_c`` are non-negative blend weights fit on the
    out-of-fold predictions. We return a *logit* (the log-odds of
    that blended probability) so the existing
    ``torch.sigmoid(_MODEL(...))`` call site in
    ``_predict_uncalibrated`` recovers ``p`` unchanged -- single-model
    and ensemble submissions then share one inference path, including
    the per-bc calibrator that runs against probabilities downstream.

    Constraint enforced at construction time: every member must share
    the same auxiliary-feature flags (``use_pool_features``,
    ``use_cluster_features``, ``use_judge_features``,
    ``use_nn_features``, ``use_subject_text_embedding``). This is
    what lets ``_predict_uncalibrated`` consult a single
    ``_MODEL_CFG`` to decide which input channels to build, instead
    of materializing every superset channel and routing per member.
    """

    def __init__(
        self,
        members,
        blend_weights,
        blend_weights_missing=None,
        force_bench_missing=None,
    ):
        super().__init__()
        if not members:
            raise RuntimeError("_EnsembleModel: empty members list")
        if len(blend_weights) != len(members):
            raise RuntimeError(
                "_EnsembleModel: blend_weights length "
                f"{len(blend_weights)} != n_members {len(members)}"
            )
        if (
            blend_weights_missing is not None
            and len(blend_weights_missing) != len(members)
        ):
            raise RuntimeError(
                "_EnsembleModel: blend_weights_missing length "
                f"{len(blend_weights_missing)} != n_members {len(members)}"
            )
        if (
            force_bench_missing is not None
            and len(force_bench_missing) != len(members)
        ):
            raise RuntimeError(
                "_EnsembleModel: force_bench_missing length "
                f"{len(force_bench_missing)} != n_members {len(members)}"
            )
        flag_keys = (
            "use_pool_features",
            "use_cluster_features",
            "use_judge_features",
            "use_nn_features",
            "use_subject_text_embedding",
        )
        ref_flags = {
            k: bool(members[0]["model_cfg"].get(k, False)) for k in flag_keys
        }
        for m in members[1:]:
            cur = {k: bool(m["model_cfg"].get(k, False)) for k in flag_keys}
            if cur != ref_flags:
                raise RuntimeError(
                    "_EnsembleModel: ensemble members disagree on auxiliary "
                    f"feature flags: ref={ref_flags} member={cur}. Re-export "
                    "with members that share these flags."
                )

        # Register every fold-model so .to() / .eval() / .cuda() propagate.
        self._member_lists: list[nn.ModuleList] = []
        self.member_names: list[str] = []
        for member in members:
            ml = nn.ModuleList(member["fold_models"])
            self._member_lists.append(ml)
            self.member_names.append(str(member.get("config_id", "")))
        # nn.ModuleList objects must be set as attributes for parameter
        # tracking. We give them stable names so torch.save inspection is
        # readable, but the runtime never relies on the names.
        for idx, ml in enumerate(self._member_lists):
            setattr(self, f"_member_{idx:02d}", ml)

        # Per-member kwarg-acceptance: only forward ``meta_override`` to
        # members whose fold-model forward declares the kwarg. Lets us
        # mix ``MetaHybrid*`` (accepts the kwarg) with ``Hybrid*`` (does
        # not) inside the same coverage-gated ensemble.
        import inspect as _inspect

        self._member_accepts_meta_override: list[bool] = []
        for ml in self._member_lists:
            accepts = False
            if len(ml) > 0:
                try:
                    sig = _inspect.signature(ml[0].forward)
                    accepts = "meta_override" in sig.parameters
                except (TypeError, ValueError):
                    accepts = False
            self._member_accepts_meta_override.append(accepts)

        # Per-member ``force_bench_missing``: when True, splice the
        # incoming ``meta_override``'s benchmark fields with row 0
        # (the ``__MISSING__`` pattern) of the member's own
        # ``bc_meta_*`` buffers before calling forward. Used for
        # members that were trained with ``p_bench=1.0`` so the
        # only trained bench-side embedding is the MISSING token --
        # at inference we must ALWAYS feed them MISSING bench input
        # to match the training distribution. Stored as a Python
        # list (not buffer) because it's pure metadata, not weights.
        self._force_bench_missing: list[bool] = [
            bool(x) for x in (force_bench_missing or [False] * len(members))
        ]

        w = torch.as_tensor(list(blend_weights), dtype=torch.float64)
        w = torch.clamp(w, min=0.0)
        s = float(w.sum().item())
        if s <= 0.0:
            w = torch.ones_like(w) / float(len(members))
        else:
            w = w / s
        self.register_buffer("blend_weights", w.to(torch.float32), persistent=False)

        # Optional coverage-conditional second weight vector. When
        # provided, the bundle interprets ``blend_weights`` as the
        # weights to use for rows whose benchmark IS in the indexer
        # (``bench_present == 1``), and ``blend_weights_missing`` for
        # cold-start rows (``bench_present == 0``). When None, the
        # ensemble blends with a single scalar weight per member as
        # before. Stored as a non-persistent buffer to mirror
        # ``blend_weights``.
        self._has_coverage_blend = blend_weights_missing is not None
        if self._has_coverage_blend:
            wm = torch.as_tensor(list(blend_weights_missing), dtype=torch.float64)
            wm = torch.clamp(wm, min=0.0)
            sm = float(wm.sum().item())
            if sm <= 0.0:
                wm = torch.ones_like(wm) / float(len(members))
            else:
                wm = wm / sm
            self.register_buffer(
                "blend_weights_missing",
                wm.to(torch.float32),
                persistent=False,
            )

    def forward(
        self,
        s,
        bc,
        ie,
        se=None,
        pool_feats=None,
        cluster_ids=None,
        judge_feats=None,
        nn_feats=None,
        meta_override=None,
        bench_present=None,
    ):
        eps = 1.0e-7
        use_per_row = (
            self._has_coverage_blend
            and bench_present is not None
        )
        bp = None
        if use_per_row:
            bp = bench_present
            if not isinstance(bp, torch.Tensor):
                bp = torch.as_tensor(bp)
            bp = bp.to(torch.float32).reshape(-1)
        p_blend = None
        for w_idx, ml in enumerate(self._member_lists):
            p_member = None
            n_folds = len(ml)
            accepts_meta = self._member_accepts_meta_override[w_idx]
            force_miss = self._force_bench_missing[w_idx]
            # Per-member meta_override splicing. When ``force_miss`` is
            # set we substitute the bench fields with row 0 of the
            # member's own ``bc_meta_*`` buffers (the MISSING pattern).
            # Subject side passes through unchanged.
            member_override = meta_override
            if (
                accepts_meta
                and force_miss
                and meta_override is not None
                and len(ml) > 0
            ):
                fold0 = ml[0]
                bc_cat_buf = getattr(fold0, "bc_meta_cat_ids", None)
                bc_num_buf = getattr(fold0, "bc_meta_num", None)
                if bc_cat_buf is not None and bc_num_buf is not None:
                    bc_cat_in = meta_override["bc_cat"]
                    bc_num_in = meta_override["bc_num"]
                    B = int(bc_cat_in.shape[0])
                    bc_cat_miss = (
                        bc_cat_buf[0:1]
                        .to(bc_cat_in.device)
                        .to(bc_cat_in.dtype)
                        .expand(B, -1)
                        .contiguous()
                    )
                    bc_num_miss = (
                        bc_num_buf[0:1]
                        .to(bc_num_in.device)
                        .to(bc_num_in.dtype)
                        .expand(B, -1)
                        .contiguous()
                    )
                    member_override = {
                        "subj_cat": meta_override["subj_cat"],
                        "subj_num": meta_override["subj_num"],
                        "bc_cat": bc_cat_miss,
                        "bc_num": bc_num_miss,
                    }
            for fold_model in ml:
                if accepts_meta and member_override is not None:
                    logit = fold_model(
                        s,
                        bc,
                        ie,
                        se,
                        pool_feats,
                        cluster_ids,
                        judge_feats,
                        nn_feats,
                        meta_override=member_override,
                    )
                else:
                    logit = fold_model(
                        s,
                        bc,
                        ie,
                        se,
                        pool_feats,
                        cluster_ids,
                        judge_feats,
                        nn_feats,
                    )
                p_fold = torch.sigmoid(logit)
                p_member = p_fold if p_member is None else (p_member + p_fold)
            p_member = p_member / float(max(1, n_folds))
            if use_per_row:
                bp_d = bp.to(p_member.device).to(p_member.dtype)
                while bp_d.dim() < p_member.dim():
                    bp_d = bp_d.unsqueeze(-1)
                w_pres = self.blend_weights[w_idx].to(p_member.dtype)
                w_miss = self.blend_weights_missing[w_idx].to(p_member.dtype)
                w_c = bp_d * w_pres + (1.0 - bp_d) * w_miss
            else:
                w_c = self.blend_weights[w_idx].to(p_member.dtype)
            contrib = w_c * p_member
            p_blend = contrib if p_blend is None else (p_blend + contrib)
        # Return a logit so the existing predict() path can sigmoid() to
        # recover the blended probability unchanged.
        p_blend = p_blend.clamp(min=eps, max=1.0 - eps)
        return torch.log(p_blend / (1.0 - p_blend))


# ---------------------------------------------------------------------------
# Calibrator (per-benchmark partial-pool intercept + new-bc type shift)
# ---------------------------------------------------------------------------
#
# Design notes:
#
#   * One-parameter intercept per benchmark plus ONE extra parameter
#     ``delta_type`` that captures a systematic shift between new-bc
#     rows (benchmarks not in _BC_TO_ID) and known-bc rows.  This is
#     the type-conditional intercept that survived red-team in
#     ``scripts/_sim_tier1_candidates.py`` and
#     ``scripts/_sim_type_sweep.py`` -- mean NLL gain ranges from
#     +0.0016 nats on honest baselines to +0.0117 nats on systematic
#     mean-shift adversarial regimes, with worst-case adversarial loss
#     of -0.00015 nats (effectively zero, well below the 0.001 nat
#     leaderboard noise floor).
#
#   * Why this beats the previous b_global+delta_bc-only calibrator:
#     with the dual-pool 95/5 acquisition, 70 of the 75 labels come
#     from new-bc rows.  The b_global fit absorbs the SAMPLE-LEVEL
#     mean shift of those new-bc rows even when the population means
#     are balanced.  That shift then mis-applies to the 80% of test
#     rows that are known-bc.  delta_type separates the new-bc
#     sample-mean from the global mean in 1 ridge-regularized
#     parameter; bc_keys that are not in _BC_TO_ID inherit
#     b_global + delta_type at apply time, while known-bc rows inherit
#     just b_global.
#
#   * The fit is a 4-stage coordinate descent:
#
#       stage 1: b_global = argmin_b sum_all BCE(logit(p)+b, y) + tau_g * b^2
#       stage 2: delta_type = argmin_d sum_{is_new} BCE(logit(p)+b_global+d, y)
#                              + tau_type * d^2     (only fit on new-bc rows)
#       stage 3: re-fit b_global with delta_type * is_new_i as per-row offset
#       stage 4: per_bc[k] = argmin_b sum_{bc=k} BCE(logit(p)+b, y)
#                              + tau_bc * (b - (b_global + delta_type * is_new_k))^2
#
#   * tau_type = 10 was picked from the tau sweep in
#     scripts/_sim_type_sweep.py over {3, 5, 10, 20, 50, 100} on six
#     regimes.  Lower tau wins bigger on real shifts but loses on
#     no-shift; higher tau is too conservative.  At tau=10, worst
#     adversarial loss is -0.00015 nats; best gain is +0.012 nats on
#     systematic mean-shift; honest baselines gain +0.0016-0.0036
#     nats.
#
#   * RIDGE_LAMBDA = 20 (global + per-bc) was carried over from the
#     previous PP_CONSERVATIVE refactor; the sweep showed lambda in
#     [15, 25] tied for lowest mean NLL.


_RIDGE_LAMBDA_GLOBAL = 20.0
_RIDGE_LAMBDA_BC = 20.0
_RIDGE_LAMBDA_TYPE = 10.0


def _sigmoid(x: float) -> float:
    if x >= 0:
        z = math.exp(-x)
        return 1.0 / (1.0 + z)
    z = math.exp(x)
    return z / (1.0 + z)


def _logit(p: float) -> float:
    p = min(max(p, EPS), 1.0 - EPS)
    return math.log(p / (1.0 - p))


def _fit_intercept_ridge(
    ps,
    ys,
    *,
    target_b: float = 0.0,
    ridge: float = _RIDGE_LAMBDA_GLOBAL,
) -> float:
    """Return ``b`` minimizing sum BCE(logit(p)+b, y) + ridge * (b - target_b)**2."""
    if not ps:
        return float(target_b)
    zs = [_logit(p) for p in ps]
    b = float(target_b)
    for _ in range(80):
        g = 2.0 * ridge * (b - target_b)
        h = 2.0 * ridge
        for z, y in zip(zs, ys):
            q = _sigmoid(z + b)
            g += q - y
            h += q * (1.0 - q)
        if h < 1e-9:
            break
        step = g / h
        new_b = b - step
        if not math.isfinite(new_b):
            break
        if abs(new_b - b) < 1e-8:
            b = new_b
            break
        b = new_b
    if not math.isfinite(b):
        return float(target_b)
    return max(-5.0, min(5.0, float(b)))


class _Calibrator:
    """Type-conditional partial-pool intercept calibrator.

    State:
      * ``b_global``     -- global intercept shift (applied to every row).
      * ``delta_type``   -- additional shift applied to NEW-bc rows only
                            (bc_key not in _BC_TO_ID at fit time).
      * ``per_bc``       -- per-benchmark full intercept (already
                            includes b_global + delta_type * is_new_for_bc).

    Routing at apply time:
        - ``per_bc[bc_key]`` if present (covers benchmarks seen in this
          round's labeled set);
        - else ``b_global + delta_type`` if bc_key is NOT in _BC_TO_ID
          (i.e. a benchmark that did not appear in training data);
        - else ``b_global`` (a training benchmark we just didn't see
          labels for this round).

    ``bc_key`` is the raw "benchmark::condition" string so each unseen
    benchmark gets its own slot (we never collapse new benchmarks to a
    shared bucket).
    """

    def __init__(self, state: dict | None = None) -> None:
        if isinstance(state, dict) and state.get("kind") == "intercept":
            self.b_global: float = float(state.get("b", 0.0))
        else:
            self.b_global = 0.0
        self.delta_type: float = 0.0
        self.per_bc: dict[str, float] = {}

    def fit_from_labeled(self, labeled_list) -> None:
        if not labeled_list:
            return
        ps: list[float] = []
        ys: list[float] = []
        bcs: list[str] = []
        is_new_list: list[float] = []
        for ex in labeled_list:
            try:
                lbl = ex.get("label")
                if lbl is None:
                    continue
                y = float(lbl)
            except (TypeError, ValueError):
                continue
            if not math.isfinite(y):
                continue
            benchmark = str(ex.get("benchmark", "") or "")
            condition = normalize_condition(ex.get("condition", "none"))
            subject_content = str(ex.get("subject_content", "") or "")
            item_content = str(ex.get("item_content", "") or "")
            try:
                p_base = _predict_uncalibrated(
                    benchmark, condition, subject_content, item_content
                )
            except Exception:
                continue
            if not math.isfinite(p_base):
                continue
            bc_key = "{0}::{1}".format(benchmark, condition)
            ps.append(float(p_base))
            ys.append(min(max(y, 0.0), 1.0))
            bcs.append(bc_key)
            is_new_list.append(0.0 if bc_key in _BC_TO_ID else 1.0)
        if not ps:
            return
        # Stage 1: initial b_global on raw ps.
        self.b_global = _fit_intercept_ridge(
            ps, ys, target_b=0.0, ridge=_RIDGE_LAMBDA_GLOBAL
        )
        # Stage 2: fit delta_type from new-bc rows only, with b_global as
        # fixed offset.  Pre-shift the ps by b_global so the existing
        # _fit_intercept_ridge can be reused.
        new_ps = []
        new_ys = []
        for i, flag in enumerate(is_new_list):
            if flag > 0.5:
                new_ps.append(_sigmoid(_logit(ps[i]) + self.b_global))
                new_ys.append(ys[i])
        if new_ps:
            self.delta_type = _fit_intercept_ridge(
                new_ps, new_ys, target_b=0.0, ridge=_RIDGE_LAMBDA_TYPE
            )
        else:
            self.delta_type = 0.0
        # Stage 3: re-fit b_global with delta_type * is_new as per-row offset.
        shifted_ps = [
            _sigmoid(_logit(ps[i]) + self.delta_type * is_new_list[i])
            for i in range(len(ps))
        ]
        self.b_global = _fit_intercept_ridge(
            shifted_ps, ys, target_b=0.0, ridge=_RIDGE_LAMBDA_GLOBAL
        )
        # Stage 4: per-bc deltas, with target = b_global + delta_type * is_new_for_bc.
        bc_to_pairs: dict[str, tuple[list[float], list[float], float]] = {}
        for p, y, bc, flag in zip(ps, ys, bcs, is_new_list):
            bucket = bc_to_pairs.setdefault(bc, ([], [], flag))
            bucket[0].append(p)
            bucket[1].append(y)
        self.per_bc = {}
        for bc_key, (lp, ly, flag) in bc_to_pairs.items():
            target = self.b_global + self.delta_type * flag
            b_bc = _fit_intercept_ridge(
                lp, ly, target_b=target, ridge=_RIDGE_LAMBDA_BC
            )
            self.per_bc[bc_key] = float(b_bc)
        try:
            n_new_benchmarks = sum(
                1 for k in self.per_bc if k not in _BC_TO_ID
            )
            LOG.info(
                "Calibrator fit: N=%d, b_global=%+.4f, delta_type=%+.4f, per_bc=%d (of which %d are NEW benchmarks)",
                len(ps),
                self.b_global,
                self.delta_type,
                len(self.per_bc),
                n_new_benchmarks,
            )
        except Exception:
            pass

    def apply(self, p: float, bc_key: str = "") -> float:
        if not math.isfinite(p):
            return DEFAULT_PROB
        if isinstance(bc_key, str) and bc_key in self.per_bc:
            b = float(self.per_bc[bc_key])
        else:
            # Unseen-this-round bc: fall back to global + type shift.
            is_new = 0.0 if (isinstance(bc_key, str) and bc_key in _BC_TO_ID) else 1.0
            b = float(self.b_global) + float(self.delta_type) * is_new
        try:
            z = _logit(p) + b
            q = _sigmoid(z)
        except Exception:
            return DEFAULT_PROB
        if not math.isfinite(q):
            return DEFAULT_PROB
        return float(min(max(q, EPS), 1.0 - EPS))


class _NNCalibrator:
    """Netflix-Prize-style nearest-neighbor calibrator.

    For each (subject, item) prediction this calibrator looks up the
    top-K nearest training items in embedding space, computes the
    similarity-weighted mean of ``(y_neighbor - p_uncal_neighbor)``
    over neighbors that have a recorded label for the same subject,
    and shifts the model's prediction by ``alpha`` times that mean.
    The state (``alpha``, ``temperature``, ``k``, ``similarity``,
    ``min_weight_sum``, ``similarity_floor``,
    ``apply_in_logit_space``) is loaded from
    ``runtime_meta.json["nn_calibrator"]``; the per-(subject, item)
    label + uncalibrated-probability table is loaded from
    ``cache/nn_residual/`` (four .npy files plus meta.json).

    When the state is absent, the loader returns a no-op instance
    (``alpha=0``) and ``apply`` is the identity. This keeps existing
    submission bundles backwards compatible.
    """

    def __init__(self, state: dict | None = None) -> None:
        st = dict(state or {})
        self.alpha: float = float(st.get("alpha", 0.0))
        self.temperature: float = float(st.get("temperature", 1.0))
        self.k: int = int(st.get("k", 16))
        self.similarity: str = str(st.get("similarity", "cosine"))
        self.min_weight_sum: float = float(st.get("min_weight_sum", 1e-3))
        self.similarity_floor: float = float(st.get("similarity_floor", 0.0))
        self.apply_in_logit_space: bool = bool(
            st.get("apply_in_logit_space", False)
        )
        # Sparse table; each is None until ``load_table`` succeeds.
        self.passrate_indptr: np.ndarray | None = None
        self.passrate_indices: np.ndarray | None = None
        self.passrate_data: np.ndarray | None = None
        self.uncal_prob_data: np.ndarray | None = None
        self.n_subjects: int = 0
        self.n_training_items: int = 0

    @property
    def has_table(self) -> bool:
        return (
            self.passrate_indptr is not None
            and self.passrate_indices is not None
            and self.passrate_data is not None
            and self.uncal_prob_data is not None
        )

    def load_table(self, table_dir: Path) -> None:
        """Load the four sparse arrays + meta. No-op on any failure."""
        try:
            meta = json.loads(
                (table_dir / "meta.json").read_text(encoding="utf-8")
            )
            self.passrate_indptr = np.load(
                table_dir / "passrate_indptr.npy"
            ).astype(np.int64, copy=False)
            self.passrate_indices = np.load(
                table_dir / "passrate_indices.npy"
            ).astype(np.int32, copy=False)
            self.passrate_data = np.load(
                table_dir / "passrate_data.npy"
            ).astype(np.float32, copy=False)
            self.uncal_prob_data = np.load(
                table_dir / "uncal_prob_data.npy"
            ).astype(np.float32, copy=False)
            self.n_subjects = int(meta.get("n_subjects", 0))
            self.n_training_items = int(meta.get("n_training_items", 0))
            LOG.info(
                "NN calibrator table loaded: n_subjects=%d n_training_items=%d nnz=%d",
                self.n_subjects,
                self.n_training_items,
                int(self.passrate_data.shape[0]),
            )
        except Exception as exc:  # noqa: BLE001
            self.passrate_indptr = None
            self.passrate_indices = None
            self.passrate_data = None
            self.uncal_prob_data = None
            LOG.info("NN calibrator table load skipped (%s)", exc)

    def _lookup(
        self, subject_id: int, neighbor_rows: np.ndarray
    ) -> tuple[np.ndarray, np.ndarray, np.ndarray]:
        if not self.has_table:
            n = neighbor_rows.shape[0]
            return (
                np.zeros(n, dtype=np.float32),
                np.zeros(n, dtype=np.float32),
                np.zeros(n, dtype=np.float32),
            )
        s = int(subject_id)
        if s < 0 or s >= int(self.n_subjects):
            n = neighbor_rows.shape[0]
            return (
                np.zeros(n, dtype=np.float32),
                np.zeros(n, dtype=np.float32),
                np.zeros(n, dtype=np.float32),
            )
        a = int(self.passrate_indptr[s])
        b = int(self.passrate_indptr[s + 1])
        if a == b:
            n = neighbor_rows.shape[0]
            return (
                np.zeros(n, dtype=np.float32),
                np.zeros(n, dtype=np.float32),
                np.zeros(n, dtype=np.float32),
            )
        sub_idx = self.passrate_indices[a:b]
        sub_y = self.passrate_data[a:b]
        sub_p = self.uncal_prob_data[a:b]
        nbr = np.asarray(neighbor_rows, dtype=np.int64)
        pos = np.searchsorted(sub_idx, nbr)
        clipped = np.clip(pos, 0, len(sub_idx) - 1)
        hit = (clipped == pos) & (sub_idx[clipped] == nbr)
        labels = np.where(hit, sub_y[clipped], 0.0).astype(np.float32)
        probs = np.where(hit, sub_p[clipped], 0.0).astype(np.float32)
        mask = hit.astype(np.float32)
        return labels, probs, mask

    def apply(
        self,
        p_uncal: float,
        subject_id: int,
        neighbor_rows: np.ndarray | None,
        neighbor_sims: np.ndarray | None,
    ) -> float:
        """Adjust ``p_uncal`` by the kNN residual term. Identity when
        the state is degenerate (alpha=0, no table, or no neighbors)."""
        if (
            float(self.alpha) == 0.0
            or not self.has_table
            or neighbor_rows is None
            or neighbor_sims is None
        ):
            return float(p_uncal)
        nbrs = np.asarray(neighbor_rows, dtype=np.int64).reshape(-1)
        sims = np.asarray(neighbor_sims, dtype=np.float32).reshape(-1)
        if nbrs.size == 0 or sims.size == 0:
            return float(p_uncal)
        K_eff = min(int(self.k), int(nbrs.shape[0]))
        nbrs = nbrs[:K_eff]
        sims = sims[:K_eff]
        ys, ps, m = self._lookup(int(subject_id), nbrs)
        if not bool(m.any()):
            return float(p_uncal)
        weights = np.clip(sims - float(self.similarity_floor), 0.0, None)
        if float(self.temperature) != 1.0:
            weights = np.power(weights, float(self.temperature))
        w = weights * m
        w_sum = float(w.sum())
        if w_sum < float(self.min_weight_sum):
            return float(p_uncal)
        if self.apply_in_logit_space:
            ys_c = np.clip(ys, EPS, 1.0 - EPS).astype(np.float64)
            ps_c = np.clip(ps, EPS, 1.0 - EPS).astype(np.float64)
            r = np.log(ys_c / (1.0 - ys_c)) - np.log(ps_c / (1.0 - ps_c))
            shift = float((w.astype(np.float64) * r).sum() / w_sum)
            p_in = float(min(max(p_uncal, EPS), 1.0 - EPS))
            logit_in = math.log(p_in / (1.0 - p_in))
            logit_out = logit_in + float(self.alpha) * shift
            try:
                q = 1.0 / (1.0 + math.exp(-logit_out))
            except OverflowError:
                q = 0.0 if logit_out < 0 else 1.0
        else:
            r = ys.astype(np.float64) - ps.astype(np.float64)
            shift = float((w.astype(np.float64) * r).sum() / w_sum)
            q = float(p_uncal) + float(self.alpha) * shift
        if not math.isfinite(q):
            return float(p_uncal)
        return float(min(max(q, EPS), 1.0 - EPS))


