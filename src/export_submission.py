def _mean_pool(last_hidden, attention_mask):
    mask = attention_mask.unsqueeze(-1).to(last_hidden.dtype)
    summed = (last_hidden * mask).sum(dim=1)
    denom = mask.sum(dim=1).clamp(min=1.0)
    return summed / denom


def _last_token_pool(last_hidden, attention_mask):
    lens = attention_mask.sum(dim=1) - 1
    lens = lens.clamp(min=0)
    batch = torch.arange(last_hidden.size(0), device=last_hidden.device)
    return last_hidden[batch, lens]


def _embed_one(text: str) -> np.ndarray:
    if _ENCODER is None:
        # Encoder failed to load (a defensive guard); return a zero vector
        # with the expected dim so the runtime still produces a usable
        # prediction via the IRT term.  The dim is read from _MODEL_CFG so
        # we don't need the encoder loaded to know it.
        dim = int(_MODEL_CFG.get("item_embed_dim", 0))
        return np.zeros(dim, dtype=np.float32)
    enc = _TOKENIZER(
        [text],
        padding=True,
        truncation=True,
        max_length=MAX_LEN,
        return_tensors="pt",
    )
    input_ids = enc["input_ids"].to(_DEVICE)
    attn = enc["attention_mask"].to(_DEVICE)
    with torch.inference_mode():
        out = _ENCODER(input_ids=input_ids, attention_mask=attn)
    last_hidden = out.last_hidden_state
    if POOLING == "cls":
        pooled = last_hidden[:, 0]
    elif POOLING == "last_token":
        pooled = _last_token_pool(last_hidden, attn)
    else:
        pooled = _mean_pool(last_hidden, attn)
    vec = pooled.float().cpu().numpy()[0]
    if not np.all(np.isfinite(vec)):
        vec = np.nan_to_num(vec, nan=0.0, posinf=0.0, neginf=0.0)
    return vec.astype(np.float32, copy=False)


def _embed_batch(texts: list) -> list:
    """Encode many texts in chunks of ENCODER_RUNTIME_BATCH_SIZE.

    Returns one float32 vector per input string, in the same order. Uses
    ``padding="longest"`` within each chunk so wasted compute scales with
    the per-chunk maximum length rather than the global one -- valuable
    when item content has a heavy length tail.
    """
    if not texts:
        return []
    if _ENCODER is None:
        # See ``_embed_one``: encoder was freed and the caller is asking
        # for items not pre-queued during acquisition. Return zero
        # vectors so the runtime stays alive.
        dim = int(_MODEL_CFG.get("item_embed_dim", 0))
        return [np.zeros(dim, dtype=np.float32) for _ in texts]
    out: list = [None] * len(texts)
    B = max(1, int(ENCODER_RUNTIME_BATCH_SIZE))
    for start in range(0, len(texts), B):
        chunk = texts[start : start + B]
        enc = _TOKENIZER(
            chunk,
            padding="longest",
            truncation=True,
            max_length=MAX_LEN,
            return_tensors="pt",
        )
        input_ids = enc["input_ids"].to(_DEVICE)
        attn = enc["attention_mask"].to(_DEVICE)
        with torch.inference_mode():
            res = _ENCODER(input_ids=input_ids, attention_mask=attn)
        last_hidden = res.last_hidden_state
        if POOLING == "cls":
            pooled = last_hidden[:, 0]
        elif POOLING == "last_token":
            pooled = _last_token_pool(last_hidden, attn)
        else:
            pooled = _mean_pool(last_hidden, attn)
        vecs = pooled.float().cpu().numpy()
        for i in range(vecs.shape[0]):
            v = vecs[i]
            if not np.all(np.isfinite(v)):
                v = np.nan_to_num(v, nan=0.0, posinf=0.0, neginf=0.0)
            out[start + i] = v.astype(np.float32, copy=False)
    return out


def _get_item_embedding(benchmark: str, condition: str, item_content: str) -> np.ndarray:
    text = item_text_for(benchmark, condition, item_content)
    key = stable_sha256(benchmark, condition, item_content)
    cached = _ITEM_EMB_CACHE.get(key)
    if cached is not None:
        return cached
    vec = _embed_one(text)
    _ITEM_EMB_CACHE[key] = vec
    return vec


def _get_subject_embedding(subject_content: str) -> np.ndarray:
    if not _MODEL_CFG.get("use_subject_text_embedding"):
        dim = int(_MODEL_CFG.get("subject_embed_dim", 0))
        return np.zeros(dim, dtype=np.float32)
    key = stable_sha256(subject_content)
    cached = _SUBJECT_EMB_CACHE.get(key)
    if cached is not None:
        return cached
    text = subject_text_for(subject_content)
    vec = _embed_one(text)
    _SUBJECT_EMB_CACHE[key] = vec
    return vec


_CENTROID_DIST_PREFIX = "centroid_dist_"

# Cache of centroid squared norms so we don't recompute them on every
# prediction (the centroid file never changes after import).
_CENTROID_NORM2_CACHE: np.ndarray | None = None


def _centroid_norm2() -> np.ndarray | None:
    """Return cached ``[k]`` squared L2 norms of the centroid rows."""
    global _CENTROID_NORM2_CACHE
    if _CLUSTER_CENTROIDS is None or _CLUSTER_CENTROIDS.size == 0:
        return None
    if _CENTROID_NORM2_CACHE is None:
        _CENTROID_NORM2_CACHE = (
            (_CLUSTER_CENTROIDS * _CLUSTER_CENTROIDS).sum(axis=1).astype(np.float32)
        )
    return _CENTROID_NORM2_CACHE


def _compute_centroid_distance_vec(
    item_emb: np.ndarray, top_m: int
) -> np.ndarray:
    """Return ``[top_m]`` squared L2 distances to the nearest centroids.

    Output is sorted ascending (matches the training-time
    :func:`src.clustering.compute_top_m_distances` schema). Returns
    zeros when the centroid artifact is missing or when the consumer
    requested more centroids than exist (degraded but non-crashing).
    """
    if top_m <= 0:
        return np.zeros(0, dtype=np.float32)
    if _CLUSTER_CENTROIDS is None or _CLUSTER_CENTROIDS.size == 0:
        return np.zeros(int(top_m), dtype=np.float32)
    c_norm2 = _centroid_norm2()
    x = item_emb.astype(np.float32)[None, :]
    C = _CLUSTER_CENTROIDS
    k_clusters = int(C.shape[0])
    # Squared L2: |x|^2 + |c|^2 - 2 x.c
    d2 = (x * x).sum(axis=1, keepdims=True) + c_norm2[None, :] - 2.0 * (x @ C.T)
    d2 = np.clip(d2, 0.0, None)[0]
    eff_m = min(int(top_m), k_clusters)
    # argpartition + sort over the partition is O(k + m log m).
    if eff_m == k_clusters:
        sorted_d2 = np.sort(d2)
    else:
        part = np.argpartition(d2, eff_m - 1)[:eff_m]
        sorted_d2 = np.sort(d2[part])
    if eff_m < int(top_m):
        # Pad with the last available value to keep the model's input
        # width stable. Padding with zero would bias the residual MLP.
        pad = np.full(int(top_m) - eff_m, sorted_d2[-1], dtype=np.float32)
        return np.concatenate([sorted_d2.astype(np.float32), pad])
    return sorted_d2.astype(np.float32)


def _compute_pool_features_vec(
    item_content: str, item_emb: np.ndarray | None = None
) -> np.ndarray:
    """Compute the z-scored pool feature vector for a single item.

    ``item_emb`` is required when ``POOL_FEATURE_NAMES`` contains any
    ``centroid_dist_*`` entries (these are computed from the embedding
    against the shipped ``cluster_centroids.npy``); for the canonical
    9-feature pool list it is ignored. Older bundles whose runtime
    meta has no centroid columns will pass ``None`` and the function
    keeps its pre-existing behaviour.
    """
    if not _MODEL_CFG.get("use_pool_features"):
        return np.zeros(0, dtype=np.float32)
    feats = compute_pool_features_runtime(item_content)
    # Pre-compute centroid distances once when needed so we don't pay
    # the GEMM cost per scalar.
    centroid_top_m = sum(
        1 for n in POOL_FEATURE_NAMES if n.startswith(_CENTROID_DIST_PREFIX)
    )
    centroid_vals: dict[str, float] = {}
    if centroid_top_m > 0 and item_emb is not None:
        d_vec = _compute_centroid_distance_vec(item_emb, centroid_top_m)
        # Map "centroid_dist_<rank>" -> distance. If the names are
        # non-contiguous (e.g. someone manually edited
        # runtime_meta.json["pool_feature_names"]), we still resolve
        # by rank index.
        ranks_seen = sorted(
            int(n[len(_CENTROID_DIST_PREFIX):])
            for n in POOL_FEATURE_NAMES
            if n.startswith(_CENTROID_DIST_PREFIX)
        )
        for slot, r in enumerate(ranks_seen):
            centroid_vals[f"{_CENTROID_DIST_PREFIX}{r}"] = float(d_vec[slot])
    out = np.zeros(len(POOL_FEATURE_NAMES), dtype=np.float32)
    for i, name in enumerate(POOL_FEATURE_NAMES):
        if name.startswith(_CENTROID_DIST_PREFIX):
            v = float(centroid_vals.get(name, 0.0))
        else:
            v = float(feats.get(name, 0.0))
        s = _POOL_STATS.get(name) or {}
        mean = float(s.get("mean", 0.0))
        std = float(s.get("std", 1.0))
        if not math.isfinite(std) or std < 1e-6:
            std = 1.0
        out[i] = (v - mean) / std
    return out


def _assign_cluster_id(item_emb: np.ndarray) -> int:
    """Assign a cluster id to an item embedding via nearest centroid.

    Returns 0 (UNK) if the centroid artifact is missing or the model
    doesn't use cluster features.
    """
    if not _MODEL_CFG.get("use_cluster_features"):
        return 0
    if _CLUSTER_CENTROIDS is None or _CLUSTER_CENTROIDS.size == 0:
        return 0
    x = item_emb.astype(np.float32)[None, :]
    C = _CLUSTER_CENTROIDS
    d2 = (x * x).sum(axis=1, keepdims=True) + (C * C).sum(axis=1)[None, :] - 2.0 * x @ C.T
    return int(d2.argmin(axis=1)[0]) + 1


def _get_nn_features(
    subject_id: int,
    item_emb: np.ndarray,
    item_cache_key: str,
    *,
    query_benchmark_id: int | None = None,
    query_benchmark_age: float | None = None,
    query_cluster_id: int | None = None,
    subject_meta_redacted: bool = False,
) -> np.ndarray:
    """Return the locked NN feature vector for this (subject, item).

    Caches results by ``(subject_id, item_cache_key, bc_id, cid, age,
    subj_redact)`` so the same pair is only computed once per round.
    Falls back to zeros if NN features were not declared at training
    time, the cache failed to load, or the subject is unseen at runtime
    (mirrors how the trainer handles UNK subjects).
    """
    if not _MODEL_CFG.get("use_nn_features"):
        return np.zeros(0, dtype=np.float32)
    dim = int(_MODEL_CFG.get("nn_feature_dim", NN_FEATURE_DIM))
    if TRAINING_CACHE is None:
        return np.zeros(dim, dtype=np.float32)
    if getattr(TRAINING_CACHE, "nn_passrate", None) is None:
        return np.zeros(dim, dtype=np.float32)
    if subject_id is None or int(subject_id) < 0:
        return np.zeros(dim, dtype=np.float32)
    cache = TRAINING_CACHE._nn_feat_cache
    age_key = (
        round(float(query_benchmark_age), 4)
        if (query_benchmark_age is not None and not (isinstance(query_benchmark_age, float) and np.isnan(query_benchmark_age)))
        else None
    )
    key = (
        int(subject_id),
        str(item_cache_key),
        int(query_benchmark_id) if query_benchmark_id is not None else None,
        int(query_cluster_id) if query_cluster_id is not None else None,
        age_key,
        bool(subject_meta_redacted),
    )
    hit = cache.get(key)
    if hit is not None:
        return hit
    try:
        vec = TRAINING_CACHE.compute_nn_features(
            query_embed=item_emb,
            subject_id=int(subject_id),
            k=NN_RUNTIME_K,
            query_benchmark_id=query_benchmark_id,
            query_benchmark_age=query_benchmark_age,
            query_cluster_id=query_cluster_id,
            subject_meta_redacted=bool(subject_meta_redacted),
            item_cache_key=str(item_cache_key),
        )
    except Exception:
        LOG.exception("TRAINING_CACHE.compute_nn_features failed; returning zeros")
        return np.zeros(dim, dtype=np.float32)
    if vec.size != dim:
        out = np.zeros(dim, dtype=np.float32)
        n = min(dim, int(vec.size))
        out[:n] = vec[:n]
        vec = out
    cache[key] = vec.astype(np.float32, copy=False)
    return cache[key]


def _get_judge_features(
    benchmark: str, condition: str, subject_content: str, item_content: str
) -> np.ndarray:
    """Return the length-4 judge feature vector for this (subject, item).

    Falls back to zeros if the judge is disabled, didn't load, or the trained
    model wasn't configured with judge features. The trained model's input
    LayerNorm absorbs the shift from zeros for the "no judge" fingerprint.
    """
    if not _MODEL_CFG.get("use_judge_features"):
        return np.zeros(0, dtype=np.float32)
    dim = int(_MODEL_CFG.get("judge_feature_dim", 4))
    if JUDGE is None:
        return np.zeros(dim, dtype=np.float32)
    try:
        vec = JUDGE.score_cached(
            benchmark=benchmark,
            condition=condition,
            subject_content=subject_content,
            item_content=item_content,
        )
    except Exception:
        LOG.exception("judge.score_cached failed; returning zeros")
        return np.zeros(dim, dtype=np.float32)
    if vec.size != dim:
        # Defensive: pad or truncate so dims match the trained head.
        out = np.zeros(dim, dtype=np.float32)
        n = min(dim, int(vec.size))
        out[:n] = vec[:n]
        return out
    return vec.astype(np.float32, copy=False)


# ---------------------------------------------------------------------------
# Uncalibrated probability (used both by predict() and by the calibrator's
# fit step on the `labeled` revealed by adaptive labeling).
# ---------------------------------------------------------------------------


def _predict_uncalibrated(
    benchmark: str,
    condition: str,
    subject_content: str,
    item_content: str,
) -> float:
    benchmark = str(benchmark or "")
    condition = normalize_condition(condition)
    subject_content = str(subject_content or "")
    item_content = str(item_content or "")

    subject_key = stable_sha256(subject_content)
    bc_key = f"{benchmark}::{condition}"

    s_id = _SUBJECT_TO_ID.get(subject_key, 0)
    bc_id = _BC_TO_ID.get(bc_key, 0)

    item_emb = _get_item_embedding(benchmark, condition, item_content)
    subject_emb = _get_subject_embedding(subject_content)
    pool_vec = _compute_pool_features_vec(item_content, item_emb)
    cluster_id = _assign_cluster_id(item_emb)
    judge_vec = _get_judge_features(benchmark, condition, subject_content, item_content)
    item_cache_key = stable_sha256(benchmark, condition, item_content)
    # Look up subject_id from the shipped indexer map first; fall back to
    # the checkpoint's indexer so we still get a usable id when the cache
    # is absent. -1 means unseen -> zero NN feature vector.
    subject_nn_id: int = -1
    if TRAINING_CACHE is not None and TRAINING_CACHE.subject_key_to_id:
        subject_nn_id = int(TRAINING_CACHE.subject_key_to_id.get(subject_key, -1))
    elif s_id > 0:
        subject_nn_id = int(s_id)

    # Resolve query metadata for the conditional NN-feature cells [15..22].
    # Each value is None / NaN / -1 when the corresponding metadata is
    # unavailable; the resolver inside ``compute_nn_features`` then
    # redacts the relevant cell to ``NN_FALLBACK_VALUE``.
    cond_query_bench_id = int(bc_id) if (bc_id is not None and bc_id > 0) else -1
    # Cluster id from ``_assign_cluster_id`` is 1-indexed (0 = UNK);
    # the conditional context uses 0-indexed cluster ids, so we drop
    # back to -1 when UNK and otherwise subtract 1.
    cond_query_cluster_id = (cluster_id - 1) if cluster_id > 0 else -1
    cond_subject_meta_redacted = bool(
        _MODEL_CFG.get("force_subject_missing")
        or False
    )
    if (
        TRAINING_CACHE is not None
        and getattr(TRAINING_CACHE, "cond_bc_id_to_age", None) is not None
        and bc_id is not None
        and 0 <= int(bc_id) < int(TRAINING_CACHE.cond_bc_id_to_age.shape[0])
    ):
        v = float(TRAINING_CACHE.cond_bc_id_to_age[int(bc_id)])
        cond_query_bench_age = v if not math.isnan(v) else None
    else:
        cond_query_bench_age = None

    nn_vec = _get_nn_features(
        subject_nn_id,
        item_emb,
        item_cache_key,
        query_benchmark_id=cond_query_bench_id,
        query_benchmark_age=cond_query_bench_age,
        query_cluster_id=cond_query_cluster_id,
        subject_meta_redacted=cond_subject_meta_redacted,
    )

    ie = torch.from_numpy(item_emb).to(_DEVICE).unsqueeze(0)
    se = torch.from_numpy(subject_emb).to(_DEVICE).unsqueeze(0) if subject_emb.size > 0 else None
    pf = (
        torch.from_numpy(pool_vec).to(_DEVICE).unsqueeze(0)
        if pool_vec.size > 0
        else None
    )
    ci = (
        torch.tensor([cluster_id], dtype=torch.long, device=_DEVICE)
        if _MODEL_CFG.get("use_cluster_features")
        else None
    )
    jf = (
        torch.from_numpy(judge_vec).to(_DEVICE).unsqueeze(0)
        if judge_vec.size > 0
        else None
    )
    nf = (
        torch.from_numpy(nn_vec).to(_DEVICE).unsqueeze(0)
        if nn_vec.size > 0
        else None
    )
    s = torch.tensor([s_id], dtype=torch.long, device=_DEVICE)
    bc = torch.tensor([bc_id], dtype=torch.long, device=_DEVICE)

    # Cold-start metadata override. Only meaningful when:
    #   * the trained checkpoint uses metadata features
    #     (``_MODEL_CFG["use_metadata_features"]``), AND
    #   * the runtime preprocessor JSON was shipped and loaded
    #     successfully (``META_PREPROCESSOR is not None``), AND
    #   * the underlying model variant exposes a ``meta_override``
    #     parameter in its forward signature.
    # For a known (s_id > 0, bc_id > 0) row the buffer lookup already
    # holds the right metadata, so the override is a no-op upgrade --
    # we send it anyway so genuinely-unseen subjects/benchmarks still
    # get a useful prediction at test time. The ensemble path also
    # accepts the kwarg now: ``_EnsembleModel`` introspects each
    # member's forward signature and forwards the kwarg only to
    # members that declare it (``MetaHybrid*``), so heterogeneous
    # ensembles that mix meta + no-meta members work transparently.
    meta_override = None
    if (
        _MODEL_CFG.get("use_metadata_features", False)
        and META_PREPROCESSOR is not None
    ):
        try:
            override_cpu = _build_meta_override(benchmark, subject_content)
            if override_cpu is not None:
                meta_override = {
                    k: v.to(_DEVICE) for k, v in override_cpu.items()
                }
        except Exception:
            LOG.exception("meta_override build failed; falling back to buffer")
            meta_override = None

    # Coverage-gated blend signal for ensemble bundles. ``bench_present``
    # is 1.0 when the row's benchmark IS in the trained indexer (so its
    # per-bc bias and metadata buffers are well-trained) and 0.0 for
    # cold-start benchmarks (where the runtime should lean on the
    # no-metadata blend partner). Single-model bundles ignore this
    # value entirely. We always compute it so the kwarg routing below
    # is uniform across bundle types.
    bench_present = torch.tensor(
        [1.0 if bc_id != 0 else 0.0],
        dtype=torch.float32,
        device=_DEVICE,
    )

    with torch.inference_mode():
        # The ensemble forward accepts both ``meta_override`` and
        # ``bench_present`` as kwargs; non-ensemble model variants
        # accept only ``meta_override``. We branch on isinstance so
        # the single-model path stays bit-identical to before.
        if isinstance(_MODEL, _EnsembleModel):
            logit = _MODEL(
                s, bc, ie, se, pf, ci, jf, nf,
                meta_override=meta_override,
                bench_present=bench_present,
            )
        elif meta_override is not None:
            logit = _MODEL(s, bc, ie, se, pf, ci, jf, nf, meta_override=meta_override)
        else:
            logit = _MODEL(s, bc, ie, se, pf, ci, jf, nf)
        prob = torch.sigmoid(logit).float().cpu().item()
    if not math.isfinite(prob):
        prob = DEFAULT_PROB
    return float(min(max(prob, EPS), 1.0 - EPS))


