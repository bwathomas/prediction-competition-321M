def normalize_condition(value: Any) -> str:
    if value is None:
        return "none"
    s = str(value)
    if s == "" or s.lower() in {"nan", "none", "null"}:
        return "none"
    return s


def stable_sha256(*parts: str) -> str:
    h = hashlib.sha256()
    for part in parts:
        h.update(str(part).encode("utf-8", errors="replace"))
        h.update(b"\x00")
    return h.hexdigest()


def item_text_for(benchmark: str, condition: str, item_content: str) -> str:
    if USE_CONTEXTUAL_ITEM_TEXT:
        body = (
            f"Benchmark: {benchmark}\n"
            f"Condition: {condition}\n"
            f"Item: {item_content}"
        )
    else:
        body = str(item_content)
    return f"{PASSAGE_PREFIX}{body}" if PASSAGE_PREFIX else body


def subject_text_for(subject_content: str) -> str:
    return (
        f"{QUERY_PREFIX}{subject_content}" if QUERY_PREFIX else str(subject_content)
    )


