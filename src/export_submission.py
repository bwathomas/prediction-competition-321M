# ---------------------------------------------------------------------------
# Calibrator (intercept-only / temperature-intercept / identity)
# ---------------------------------------------------------------------------


def _sigmoid(x: float) -> float:
    if x >= 0:
        z = math.exp(-x)
        return 1.0 / (1.0 + z)
    z = math.exp(x)
    return z / (1.0 + z)


def _logit(p: float) -> float:
    p = min(max(p, EPS), 1.0 - EPS)
    return math.log(p / (1.0 - p))


class _Calibrator:
    """Identity by default; replaced in-place by fit_from_labeled()."""

    def __init__(self, state: dict | None = None):
        self.state: dict = dict(state or {"kind": "identity"})

    def apply(self, p: float) -> float:
        if not math.isfinite(p):
            return DEFAULT_PROB
        kind = self.state.get("kind", "identity")
        if kind == "intercept":
            z = _logit(p) + float(self.state.get("b", 0.0))
            return min(max(_sigmoid(z), EPS), 1.0 - EPS)
        if kind == "temp_intercept":
            T = max(0.1, float(self.state.get("T", 1.0)))
            b = float(self.state.get("b", 0.0))
            z = _logit(p) / T + b
            return min(max(_sigmoid(z), EPS), 1.0 - EPS)
        return min(max(p, EPS), 1.0 - EPS)

    def fit_from_labeled(self, labeled_list: list[dict]) -> None:
        if not labeled_list:
            return
        ps: list[float] = []
        ys: list[float] = []
        for ex in labeled_list:
            try:
                y = float(ex.get("label"))
            except (TypeError, ValueError):
                continue
            p_base = _predict_uncalibrated(
                ex.get("benchmark", ""),
                ex.get("condition", "none"),
                ex.get("subject_content", ""),
                ex.get("item_content", ""),
            )
            if math.isfinite(y) and math.isfinite(p_base):
                ys.append(min(max(y, 0.0), 1.0))
                ps.append(p_base)
        if not ps:
            return
        yb = [1 if v >= 0.5 else 0 for v in ys]
        if sum(yb) == 0 or sum(yb) == len(yb):
            return  # degenerate: identity is safer
        if len(ps) >= 30:
            self.state = _fit_temp_intercept(ps, ys)
        elif len(ps) >= 5:
            self.state = _fit_intercept_only(ps, ys)


def _fit_intercept_only(ps: list[float], ys: list[float]) -> dict:
    z = np.log(np.clip(ps, EPS, 1 - EPS)) - np.log(np.clip([1 - p for p in ps], EPS, 1 - EPS))
    y = np.asarray(ys, dtype=float)
    b = 0.0
    for _ in range(50):
        pred = 1.0 / (1.0 + np.exp(-(z + b)))
        grad = float((pred - y).mean())
        hess = float((pred * (1.0 - pred)).mean()) + 1e-6
        step = grad / hess
        b -= step
        if abs(step) < 1e-6:
            break
    if not math.isfinite(b):
        return {"kind": "identity"}
    return {"kind": "intercept", "b": float(b)}


def _fit_temp_intercept(ps: list[float], ys: list[float]) -> dict:
    z = np.log(np.clip(ps, EPS, 1 - EPS)) - np.log(np.clip([1 - p for p in ps], EPS, 1 - EPS))
    y = np.asarray(ys, dtype=float)
    T, b = 1.0, 0.0
    for _ in range(100):
        zt = z / T + b
        pred = 1.0 / (1.0 + np.exp(-zt))
        err = pred - y
        d_b = float(err.mean())
        d_a = float((err * z).mean())
        h_b = float((pred * (1 - pred)).mean()) + 1e-6
        h_a = float((pred * (1 - pred) * z * z).mean()) + 1e-6
        new_b = b - d_b / h_b
        new_a = (1.0 / T) - d_a / h_a
        new_T = 1.0 / max(0.1, new_a)
        if not (math.isfinite(new_b) and math.isfinite(new_T)):
            return {"kind": "identity"}
        if abs(new_b - b) + abs(new_T - T) < 1e-6:
            T, b = new_T, new_b
            break
        T, b = new_T, new_b
    return {"kind": "temp_intercept", "T": float(T), "b": float(b)}


# ---------------------------------------------------------------------------
# Training-item cache (nearest-neighbor lookup over training items).
#
# This is the int8-quantized (and optionally PCA-projected) snapshot of the
# *training* item embedding matrix. It lets predict() find similar training
# items for a test query without round-tripping the encoder over the whole
# training set at every test call.
#
# By contract this cache is for *training* items only: at test time we look
# up neighbors of a test query inside the training set. We never read it as
# ground truth for a test item.
# ---------------------------------------------------------------------------


class _TrainingItemCache:
    """Quantized training-item embeddings + (optional) FAISS / cluster table."""

    def __init__(self, cache_dir: Path):
        self.cache_dir = Path(cache_dir)
        meta_path = self.cache_dir / "cache_meta.json"
        if not meta_path.exists():
            raise FileNotFoundError(f"cache_meta.json not found at {meta_path}")
        with open(meta_path, "r", encoding="utf-8") as fh:
            self.meta: dict = json.load(fh)

        embeddings_path = self.cache_dir / "embeddings_int8.npy"
        scales_path = self.cache_dir / "scales.npy"
        pca_path = self.cache_dir / "pca.npy"
        keys_path = self.cache_dir / "item_keys.parquet"

        self.embeddings_q: np.ndarray = np.load(embeddings_path)
        self.scales: np.ndarray = np.load(scales_path).astype(np.float32)
        self.pca: np.ndarray | None = (
            np.load(pca_path).astype(np.float32) if pca_path.exists() else None
        )
        try:
            import pandas as _pd  # type: ignore

            self.keys = _pd.read_parquet(keys_path)
        except Exception:
            self.keys = None
        self._index: object | None = None
        self._index_path = self.cache_dir / "faiss.index"
        self._dequant_cache: np.ndarray | None = None
        # Optional per-subject cluster pass-rate table.
        self.subject_cluster_passrates: np.ndarray | None = None
        self.subject_passrates_sparse: object | None = None
        self.subject_key_to_row: dict[str, int] = {}
        spp_dense = self.cache_dir / "subject_cluster_passrates.npy"
        spp_sparse = self.cache_dir / "subject_passrates.npz"
        subject_keys_path = self.cache_dir / "subject_keys.parquet"
        if subject_keys_path.exists():
            try:
                import pandas as _pd  # type: ignore

                skdf = _pd.read_parquet(subject_keys_path)
                self.subject_key_to_row = {
                    str(k): int(i) for i, k in zip(skdf["row_index"], skdf["subject_key"])
                }
            except Exception:
                self.subject_key_to_row = {}
        if spp_dense.exists():
            try:
                self.subject_cluster_passrates = np.load(spp_dense).astype(np.float32)
            except Exception:
                self.subject_cluster_passrates = None
        if spp_sparse.exists():
            try:
                from scipy import sparse as _sparse  # type: ignore

                self.subject_passrates_sparse = _sparse.load_npz(spp_sparse)
            except Exception:
                self.subject_passrates_sparse = None

        # NN-feature cache. Same sparse format as `subject_passrates.npz`
        # above but always keyed by the trainer's subject indexer (so the
        # row index matches `subject_key_to_id`); paired with a binary
        # mask matrix so we can distinguish 0-passrate from no-data.
        self.nn_passrate: object | None = None
        self.nn_passrate_mask: object | None = None
        self.nn_cfg: dict = {}
        self.subject_key_to_id: dict[str, int] = {}
        self._nn_feat_cache: dict[tuple[int, str], np.ndarray] = {}
        nn_pr_path = self.cache_dir / "subject_passrate.npz"
        nn_mask_path = self.cache_dir / "subject_passrate_mask.npz"
        nn_cfg_path = self.cache_dir / "nn_features_config.json"
        sk2id_path = self.cache_dir / "subject_key_to_id.json"
        if nn_pr_path.exists() and nn_mask_path.exists():
            try:
                from scipy import sparse as _sparse  # type: ignore

                self.nn_passrate = _sparse.load_npz(nn_pr_path)
                self.nn_passrate_mask = _sparse.load_npz(nn_mask_path)
            except Exception as exc:  # noqa: BLE001
                LOG.warning("NN passrate sparse load failed: %s", exc)
                self.nn_passrate = None
                self.nn_passrate_mask = None
        if nn_cfg_path.exists():
            try:
                with open(nn_cfg_path, "r", encoding="utf-8") as fh:
                    self.nn_cfg = dict(json.load(fh) or {})
            except Exception:
                self.nn_cfg = {}
        if sk2id_path.exists():
            try:
                with open(sk2id_path, "r", encoding="utf-8") as fh:
                    raw = json.load(fh) or {}
                self.subject_key_to_id = {
                    str(k): int(v) for k, v in raw.items()
                }
            except Exception:
                self.subject_key_to_id = {}

    def _ensure_index(self) -> None:
        if self._index is not None:
            return
        if not self._index_path.exists():
            return
        try:
            import faiss  # type: ignore

            self._index = faiss.read_index(str(self._index_path))
        except Exception as exc:  # noqa: BLE001
            LOG.warning("FAISS read failed (%s); falling back to brute-force", exc)
            self._index = None

    def project(self, embed: np.ndarray) -> np.ndarray:
        """Apply the same PCA used at export time. No-op if PCA missing."""
        x = np.asarray(embed, dtype=np.float32)
        if self.pca is None:
            return x
        return (x @ self.pca).astype(np.float32)

    def _dequantized(self) -> np.ndarray:
        """Lazy fp32 reconstruction (only built when the FAISS index missing)."""
        if self._dequant_cache is None:
            self._dequant_cache = self.embeddings_q.astype(np.float32) * self.scales[:, None]
        return self._dequant_cache

    def nearest(self, query_embed: np.ndarray, k: int = 10) -> tuple[np.ndarray, np.ndarray]:
        """Return (indices, scores). Higher score = more similar (inner product).

        The query is the *raw* fp32/fp16 encoder output. We apply the same
        projection used at export time before lookup.
        """
        q = self.project(query_embed).reshape(1, -1)
        self._ensure_index()
        if self._index is not None:
            try:
                D, I = self._index.search(np.ascontiguousarray(q, dtype=np.float32), int(k))
                return I[0].astype(np.int64), D[0].astype(np.float32)
            except Exception as exc:  # noqa: BLE001
                LOG.warning("FAISS search failed (%s); brute-force fallback", exc)
        recon = self._dequantized()
        sims = recon @ q[0]
        kk = min(int(k), recon.shape[0])
        topk = np.argpartition(-sims, kk - 1)[:kk] if kk < recon.shape[0] else np.arange(recon.shape[0])
        order = np.argsort(-sims[topk])
        return topk[order].astype(np.int64), sims[topk][order].astype(np.float32)

    def compute_nn_features(
        self,
        query_embed: np.ndarray,
        subject_id: int,
        *,
        k: int | None = None,
    ) -> np.ndarray:
        """Return the locked 8-scalar NN feature vector for a (subject, item).

        Steps:
        1. Apply the cache's PCA projection (no-op if PCA missing).
        2. Query the nearest neighbors via FAISS / brute-force.
        3. Look up per-(subject, neighbor) passrate + mask from the sparse
           matrices shipped with the cache.
        4. Aggregate via the same ``_aggregate_nn_features`` helper used at
           training time (the function is copied verbatim into this file
           by ``src/export_submission.py``; if you change one, change both).
        """
        dim = NN_FEATURE_DIM
        if (
            self.nn_passrate is None
            or self.nn_passrate_mask is None
            or subject_id is None
            or subject_id < 0
        ):
            return np.zeros(dim, dtype=np.float32)
        kk = int(k or NN_RUNTIME_K)
        if kk < 1:
            return np.zeros(dim, dtype=np.float32)
        idx, sims = self.nearest(query_embed, k=kk)
        if idx.size == 0:
            return np.zeros(dim, dtype=np.float32)
        n_rows = self.nn_passrate.shape[0]
        if subject_id >= n_rows:
            return np.zeros(dim, dtype=np.float32)
        row_pr = self.nn_passrate.getrow(int(subject_id))
        row_mk = self.nn_passrate_mask.getrow(int(subject_id))
        n_items = int(self.nn_passrate.shape[1])
        passrates = np.zeros(kk, dtype=np.float32)
        masks = np.zeros(kk, dtype=np.float32)
        if row_pr.nnz > 0:
            cols = row_pr.indices
            vals = row_pr.data
            order = np.argsort(cols)
            sorted_cols = cols[order]
            sorted_vals = vals[order]
            valid_idx = np.clip(idx, 0, n_items - 1)
            pos = np.searchsorted(sorted_cols, valid_idx)
            pos_clipped = np.clip(pos, 0, sorted_cols.size - 1)
            hit = (pos < sorted_cols.size) & (sorted_cols[pos_clipped] == valid_idx)
            passrates = np.where(hit, sorted_vals[pos_clipped], 0.0).astype(
                np.float32
            )
        if row_mk.nnz > 0:
            mcols = row_mk.indices
            order = np.argsort(mcols)
            sorted_m = mcols[order]
            valid_idx = np.clip(idx, 0, n_items - 1)
            pos = np.searchsorted(sorted_m, valid_idx)
            pos_clipped = np.clip(pos, 0, sorted_m.size - 1)
            hit = (pos < sorted_m.size) & (sorted_m[pos_clipped] == valid_idx)
            masks = hit.astype(np.float32)
        feats = _aggregate_nn_features(
            passrates,
            masks,
            sims.astype(np.float32),
            fallback_value=NN_FALLBACK_VALUE,
            top1_missing_sentinel=NN_TOP1_MISSING_SENTINEL,
        )
        return feats.reshape(-1)[:dim].astype(np.float32, copy=False)

    def subject_cluster_features(
        self,
        subject_content: str,
        neighbor_indices: np.ndarray,
        neighbor_scores: np.ndarray,
    ) -> dict[str, float] | None:
        """Aggregate per-cluster pass rates for the NN items of `subject_content`.

        Returns ``None`` if no per-subject lookup table is bundled, or if the
        subject is unseen. Otherwise returns a small dict of summary stats
        (mean, max, weighted mean by similarity) suitable for use as
        additional features inside a model variant that consumes them.
        """
        if self.subject_cluster_passrates is None or self.keys is None:
            return None
        key = stable_sha256(str(subject_content or ""))
        row = self.subject_key_to_row.get(key)
        if row is None:
            return None
        # Look up cluster ids of the neighbor items.
        if "cluster_id" not in self.keys.columns:
            return None
        clusters_for_neighbors = self.keys["cluster_id"].to_numpy(dtype=np.int64)
        try:
            cluster_ids = clusters_for_neighbors[neighbor_indices]
        except Exception:
            return None
        rates = self.subject_cluster_passrates[row][cluster_ids]
        weights = np.clip(neighbor_scores, 0.0, None)
        if float(weights.sum()) < 1e-9:
            weights = np.ones_like(weights)
        weighted = float((rates * weights).sum() / max(float(weights.sum()), 1e-9))
        return {
            "nn_passrate_mean": float(rates.mean()) if rates.size else 0.0,
            "nn_passrate_max": float(rates.max()) if rates.size else 0.0,
            "nn_passrate_min": float(rates.min()) if rates.size else 0.0,
            "nn_passrate_weighted_mean": weighted,
        }


