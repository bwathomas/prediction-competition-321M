def export_run(
    *,
    result: TrainResult,
    encoder_cfg: Mapping,
    submission_dir: str | os.PathLike[str] = "submission",
    include_labeling: bool = True,
    extra_models_txt: list[str] | None = None,
    default_calibrator: Mapping | None = None,
    pool_stats_path: str | os.PathLike[str] | None = None,
    cluster_centroids_path: str | os.PathLike[str] | None = None,
    pool_feature_names: list[str] | None = None,
    training_cache_dir: str | os.PathLike[str] | None = None,
    judge_cfg: Mapping | None = None,
    nn_features_cfg: Mapping | None = None,
    lora_cfg: Mapping | None = None,
    lora_adapter_dir: str | os.PathLike[str] | None = None,
    lora_head_checkpoint: str | os.PathLike[str] | None = None,
    ship_training_cache: bool = False,
    ship_requirements_txt: bool = False,
) -> Path:
    """Materialize the submission folder from a single trained run.

    All exports produced by this function ship the **streamed-flush
    runtime architecture** ("runtime_architecture": "streamed_flush_v1"
    in ``runtime_meta.json``):

    - ``model.py`` forces HF offline mode (HF_HUB_OFFLINE,
      TRANSFORMERS_OFFLINE, HF_DATASETS_OFFLINE) at the top of the file,
      *before* importing transformers / huggingface_hub.  The Codabench
      runner blocks outbound traffic; without these env vars, even a
      fully-cached ``from_pretrained`` raises PAIEC-NETWORK-001.
    - ``labeling.py`` is enqueue-only: ``acquisition_function`` calls
      ``model._enqueue_for_batch(...)`` for every candidate the platform
      surfaces, which appends to the encoder + judge queues and
      *opportunistically fires AT MOST one small batch inline* (judge
      bs=8 priority, then encoder bs=16) whenever a queue crosses its
      threshold.  This bounds per-call wall time to ~100-200 ms while
      still achieving full batched throughput.
    - ``predict()`` then only drains the residual (each queue is
      < its batch size, so the residual flush is one tiny final batch
      per queue, < 1.5 s total) and falls into a cache lookup.

    This avoids the per-call PAIEC-TIMEOUT-001 hit that the prior
    "drain everything inside the first predict()" architecture took on
    ~256 k acquisition workloads.  Both 4 B-param bf16 models stay
    co-resident on the L4 for the entire round; no encoder eviction.

    If you pass ``include_labeling=False`` the streamed-flush path is
    architecturally disabled (no queue gets populated), and ``predict()``
    falls back to the original bs=1 per-call inference path. The bundle
    is still functionally correct, just ~10-15x slower at runtime. We
    log a warning when this happens; flip it back on for any real
    submission.

    The caller chooses *which* run to export (the notebook offers an
    ipywidgets dropdown or a ``SELECTED_RUN_ID`` fallback variable).

    If the exported run uses pool features and/or cluster embeddings, point
    ``pool_stats_path`` / ``cluster_centroids_path`` at the artifacts so the
    submission bundle can reconstruct them at test time. Both default to the
    standard locations under ``artifacts/`` if omitted.

    If ``training_cache_dir`` is provided (the quantized training-item cache
    written by ``bundle_training_cache``), its contents are copied into
    ``submission/cache/`` for nearest-neighbor lookup at test time.

    Single source of truth: the checkpoint's ``model_cfg`` decides whether
    NN / judge features are actually used at inference time. If the
    checkpoint declares ``use_nn_features=True`` but the caller passes
    ``nn_features_cfg=None`` (or fails to ship the NN cache), or
    ``use_judge_features=True`` without a usable ``judge_cfg``, we raise
    rather than silently shipping a bundle whose runtime feeds the trained
    head all-zero feature vectors. This is what produced the
    ``submission_judge`` regression: trainer set ``use_nn_features=True``
    but the export pipeline got ``nn_features_cfg=None`` and the runtime
    silently zero-filled the 8-dim NN slot at test time.

    Returns the submission directory path.
    """
    import torch as _torch  # local import: keep module import cheap

    if not include_labeling:
        LOG.warning(
            "export_run: include_labeling=False -- the streamed-flush "
            "architecture is disabled (acquisition_function won't be "
            "called by the platform, so model._enqueue_for_batch never "
            "fires). predict() will fall back to bs=1 inference and the "
            "bundle will run ~10-15x slower at runtime. Re-enable "
            "include_labeling=True for any non-diagnostic submission."
        )

    sub = Path(submission_dir)
    artifacts = sub / "artifacts"
    if sub.exists():
        # Wipe stale state from previous exports so we don't ship phantom files.
        shutil.rmtree(sub)
    artifacts.mkdir(parents=True, exist_ok=True)

    # If the caller is exporting a LoRA run, ``lora_head_checkpoint`` is the
    # head .pt the LoRA loop wrote (head + IRT + subject emb + feature
    # consumer state dict) -- *not* the base head-only checkpoint. We need
    # to ship THAT, not the pre-LoRA head, because the trained head was
    # updated jointly with the adapter and the runtime must see the
    # post-LoRA head weights to make consistent predictions.
    ckpt_src = (
        Path(lora_head_checkpoint)
        if lora_head_checkpoint
        else Path(result.checkpoint_path)
    )
    if not ckpt_src.exists():
        raise FileNotFoundError(f"Checkpoint not found at {ckpt_src}")
    shutil.copy2(ckpt_src, artifacts / "checkpoint.pt")

    # Read the *trained* model_cfg so it -- not any ambient notebook flag --
    # decides whether NN / judge features must be wired through at runtime.
    try:
        _ckpt = _torch.load(ckpt_src, map_location="cpu", weights_only=False)
    except Exception as exc:  # noqa: BLE001
        raise RuntimeError(
            f"export_run: could not read checkpoint {ckpt_src} to verify model_cfg: {exc}"
        ) from exc
    ckpt_model_cfg = dict(_ckpt.get("model_cfg") or {})

    # NB: ``ckpt_model_cfg`` is read *only* to inspect feature flags here.
    # We intentionally do not mutate it -- the checkpoint's model_cfg is
    # the single source of truth for tensor shapes, and the runtime
    # template reads it directly from the on-disk checkpoint at module
    # init. ``use_cluster_features=True`` combined with
    # ``cluster_embed_dim=0`` is a valid intentional state (cluster
    # channel was disabled at training time); the previous "repair" of
    # coercing it to 16 was the root cause of the
    # ``size mismatch for residual.norm.weight`` crash at module init.

    ckpt_uses_nn = bool(ckpt_model_cfg.get("use_nn_features", False))
    ckpt_uses_judge = bool(ckpt_model_cfg.get("use_judge_features", False))
    ckpt_nn_feature_dim = int(ckpt_model_cfg.get("nn_feature_dim", 0))
    ckpt_judge_feature_dim = int(ckpt_model_cfg.get("judge_feature_dim", 0))

    # --- NN features: enforce consistency between checkpoint, cache, config ---
    if ckpt_uses_nn:
        if nn_features_cfg is None:
            raise RuntimeError(
                "export_run: checkpoint declares use_nn_features=True "
                f"(nn_feature_dim={ckpt_nn_feature_dim}) but the caller passed "
                "nn_features_cfg=None. The runtime would silently feed zeros "
                "into the trained NN slot. Pass the same nn_features_cfg + "
                "subject_to_id mapping that bundle_training_cache used."
            )
        if training_cache_dir is None:
            raise RuntimeError(
                "export_run: checkpoint declares use_nn_features=True but "
                "training_cache_dir is None. The NN-features sparse passrate "
                "files live inside the training cache."
            )
        cache_src = Path(training_cache_dir)
        required_nn_files = (
            "subject_passrate.npz",
            "subject_passrate_mask.npz",
            "subject_key_to_id.json",
            "nn_features_config.json",
        )
        missing = [f for f in required_nn_files if not (cache_src / f).exists()]
        if missing:
            raise RuntimeError(
                "export_run: checkpoint declares use_nn_features=True but the "
                f"training cache at {cache_src} is missing required NN files: "
                f"{missing}. Re-run bundle_training_cache with a non-None "
                "nn_features_cfg AND subject_to_id mapping so cache_export "
                "writes the singular-name 'subject_passrate.npz' (etc.)."
            )
    elif nn_features_cfg is not None and bool(
        (nn_features_cfg or {}).get("enabled", False)
    ):
        LOG.warning(
            "export_run: nn_features_cfg.enabled=True but checkpoint has "
            "use_nn_features=False. Ignoring caller's nn_features_cfg; "
            "shipping the bundle without NN-feature runtime metadata."
        )
        nn_features_cfg = None

    # --- Judge features: enforce consistency between checkpoint and judge_cfg ---
    if ckpt_uses_judge:
        jcfg_chk = dict(judge_cfg or {})
        if not (
            bool(jcfg_chk.get("enabled", False))
            and bool(jcfg_chk.get("ship_at_runtime", True))
            and str(jcfg_chk.get("model_id", ""))
        ):
            raise RuntimeError(
                "export_run: checkpoint declares use_judge_features=True "
                f"(judge_feature_dim={ckpt_judge_feature_dim}) but judge_cfg is "
                "missing one of {enabled, ship_at_runtime, model_id}. The "
                "runtime would silently feed zeros into the trained judge slot."
            )
    elif judge_cfg is not None and bool((judge_cfg or {}).get("enabled", False)):
        LOG.warning(
            "export_run: judge_cfg.enabled=True but checkpoint has "
            "use_judge_features=False. Shipping the bundle without judge "
            "runtime metadata; trained head has no judge slot to feed."
        )
        judge_cfg = None

    # Optional pool-feature stats and cluster centroids. We always copy what
    # we can find so the submission keeps working even if the model variant
    # is later swapped from non-pool to pool.
    pool_src = Path(pool_stats_path) if pool_stats_path else Path("artifacts/item_features/pool_features_stats.json")
    if pool_src.exists():
        shutil.copy2(pool_src, artifacts / "pool_features_stats.json")
    centroids_src = (
        Path(cluster_centroids_path)
        if cluster_centroids_path
        else Path("artifacts/cluster_centroids.npy")
    )
    if centroids_src.exists():
        shutil.copy2(centroids_src, artifacts / "cluster_centroids.npy")

    # Optional training-item cache (quantized + PCA + FAISS). Copied to
    # ``submission/cache/`` so the runtime can mmap it for NN lookup.
    #
    # Default is OFF (``ship_training_cache=False``). Every 114 MB bundle
    # that shipped the cache directory has failed PAIEC-UNKNOWN-001 on
    # Codabench within 1-5 minutes; the 15 MB slim bundle (no cache) was
    # the only one that ever completed. The runtime ``_get_nn_features``
    # falls back to ``np.zeros(dim)`` when ``TRAINING_CACHE is None`` so
    # skipping the cache costs the NN feature signal but keeps the
    # bundle inside the platform's operational envelope. Flip the
    # ``ship_training_cache`` flag on (or set
    # ``submission.ship_training_cache: true`` in ``configs/default.yaml``)
    # only after verifying the platform accepts the larger bundle.
    if not ship_training_cache:
        if training_cache_dir is not None:
            LOG.info(
                "Skipping training-cache bundling (ship_training_cache=False). "
                "training_cache_dir=%s is available locally for evaluation "
                "but will NOT be copied into submission/cache/. The runtime "
                "will fall back to zero NN features.",
                training_cache_dir,
            )
    elif training_cache_dir is not None:
        src_cache = Path(training_cache_dir)
        if src_cache.exists():
            dst_cache = sub / "cache"
            if dst_cache.exists():
                shutil.rmtree(dst_cache)
            shutil.copytree(src_cache, dst_cache)
            LOG.info("Bundled training cache from %s -> %s", src_cache, dst_cache)
        else:
            LOG.warning(
                "training_cache_dir=%s does not exist; skipping cache bundle",
                src_cache,
            )

    # Normalize the judge block for the runtime. We persist the locked
    # prompt template + yes/no token lists so the runtime never diverges
    # from training-time scoring -- changing them invalidates the cache.
    # NB: ``enabled`` is forced to the checkpoint's verdict so the runtime
    # cannot load a judge model the trained head was never connected to,
    # and cannot skip a judge model the head is expecting.
    jcfg = dict(judge_cfg or {})
    # IMPORTANT: ``judge.batch_size`` in the YAML / training cfg refers to
    # the *training-time* judge-scoring batch (default 256 on A100). The
    # *runtime* judge batch is a separate knob -- it gates the bs used
    # inside ``_LLMJudgeRuntime.score_batch`` at inference time on the
    # platform's GPU (L4, 24 GB).
    #
    # The default of 8 is the safe ceiling for the streamed-flush
    # architecture, where both 4 B-param bf16 models remain co-resident
    # on the L4 for the entire round (no encoder eviction).  The judge
    # then has only ~ 8 GB of activations headroom after the encoder's
    # ~ 8 GB of weights, so bs=8 is the largest pad-longest batch that
    # reliably fits.  Raise via ``judge_cfg["runtime_batch_size"]`` only
    # if you've verified larger sizes don't OOM on the target tier.
    runtime_judge_bs = int(
        jcfg.get(
            "runtime_batch_size",
            8 if int(jcfg.get("batch_size", 8) or 8) > 64 else jcfg.get("batch_size", 8),
        )
    )
    judge_block = {
        "enabled": bool(ckpt_uses_judge),
        "ship_at_runtime": bool(jcfg.get("ship_at_runtime", True)),
        "model_id": str(jcfg.get("model_id", "")),
        # Kept for forensics / log lines; the runtime never reads this field.
        "batch_size": int(jcfg.get("batch_size", 16)),
        # The streamed-flush runtime path reads exactly this field.
        "runtime_batch_size": runtime_judge_bs,
        "max_prompt_tokens": int(jcfg.get("max_prompt_tokens", 1024)),
        "bf16": bool(jcfg.get("bf16", True)),
        "use_flash_attention": bool(jcfg.get("use_flash_attention", True)),
        "trust_remote_code": bool(jcfg.get("trust_remote_code", False)),
        "suffix_reserve_tokens": int(jcfg.get("suffix_reserve_tokens", 256)),
        "yes_tokens": list(
            jcfg.get("yes_tokens", (" yes", "yes", " Yes", "Yes"))
        ),
        "no_tokens": list(
            jcfg.get("no_tokens", (" no", "no", " No", "No"))
        ),
        "prompt_template": str(
            jcfg.get(
                "prompt_template",
                (
                    "You will see a description of an AI subject and an evaluation item. "
                    "Decide whether the subject would answer the item correctly. "
                    "Reply with a single token: yes or no.\n\n"
                    "Benchmark: {benchmark}\n"
                    "Condition: {condition}\n"
                    "Subject: {subject_content}\n"
                    "Item: {item_content}\n"
                    "Answer:"
                ),
            )
        ),
        "feature_in_residual": bool(jcfg.get("feature_in_residual", True)),
    }

    # --- LoRA adapter / merged-encoder handling --------------------------
    # Two supported export modes (set via ``lora_cfg.export_mode``):
    #
    # 1. ``adapter_only`` (default): copy the LoRA adapter dir into
    #    ``submission/lora_adapter/`` and let the runtime apply +
    #    merge_and_unload it onto the stock encoder at import. ``models.txt``
    #    declares the stock encoder; ``requirements.txt`` declares ``peft``.
    #    Net effect: tiny ZIP (~10-50 MB adapter), runtime is byte-equivalent
    #    to having shipped the merged encoder. Self-contained, no HF auth.
    #
    # 2. ``hf_upload``: caller is responsible for uploading the merged
    #    encoder to a private HF repo BEFORE running export_run; here we
    #    just rewrite ENCODER_ID to point at that repo and leave the
    #    runtime to load it like any other encoder. The bundle ships
    #    nothing extra and ``peft`` is not required at runtime. Slightly
    #    cleaner deployment but adds an external dependency (the repo).
    lora_block: dict | None = None
    lora_runtime_id_override: str | None = None
    lora_extra_models: list[str] = []
    lora_requirements_addendum = ""
    if lora_cfg is not None:
        mode = str(lora_cfg.get("export_mode", "adapter_only"))
        if mode == "adapter_only":
            if not lora_adapter_dir:
                raise RuntimeError(
                    "export_run: lora_cfg.export_mode='adapter_only' but no "
                    "lora_adapter_dir was passed. Point it at the directory "
                    "containing adapter_config.json + adapter weights "
                    "(e.g. the LoRA run's `best/adapter/`)."
                )
            adapter_src = Path(lora_adapter_dir)
            if not adapter_src.exists():
                raise RuntimeError(
                    f"export_run: lora_adapter_dir={adapter_src} does not exist"
                )
            adapter_dst = sub / "lora_adapter"
            if adapter_dst.exists():
                shutil.rmtree(adapter_dst)
            shutil.copytree(adapter_src, adapter_dst)
            adapter_size_mb = sum(
                p.stat().st_size for p in adapter_dst.rglob("*") if p.is_file()
            ) / (1024 * 1024)
            LOG.info(
                "Bundled LoRA adapter from %s -> %s (%.2f MB)",
                adapter_src,
                adapter_dst,
                adapter_size_mb,
            )
            lora_block = {
                "mode": "adapter_only",
                "adapter_rel_path": "lora_adapter",
                "adapter_size_mb": float(adapter_size_mb),
                "base_encoder_model_id": str(encoder_cfg["model_id"]),
                "r": int(lora_cfg.get("r", 16)),
                "alpha": int(lora_cfg.get("alpha", 32)),
                "target_modules": list(
                    lora_cfg.get(
                        "target_modules", ["q_proj", "k_proj", "v_proj", "o_proj"]
                    )
                ),
                "layers_to_transform": (
                    list(lora_cfg.get("layers_to_transform"))
                    if lora_cfg.get("layers_to_transform")
                    else None
                ),
            }
            lora_requirements_addendum = _RUNTIME_REQUIREMENTS_LORA_LINE
        elif mode == "hf_upload":
            merged_repo = str(lora_cfg.get("hf_upload_repo") or "")
            if not merged_repo or "{user}" in merged_repo:
                raise RuntimeError(
                    "export_run: lora_cfg.export_mode='hf_upload' requires "
                    "lora_cfg.hf_upload_repo to be a resolved HF repo id "
                    "(e.g. 'myuser/qwen3-embedding-4b-lora-merged'). The "
                    "notebook is responsible for uploading the merged "
                    "encoder to this repo BEFORE calling export_run."
                )
            lora_runtime_id_override = merged_repo
            lora_extra_models = [merged_repo]
            lora_block = {
                "mode": "hf_upload",
                "merged_encoder_repo": merged_repo,
                "base_encoder_model_id": str(encoder_cfg["model_id"]),
                "r": int(lora_cfg.get("r", 16)),
                "alpha": int(lora_cfg.get("alpha", 32)),
                "target_modules": list(
                    lora_cfg.get(
                        "target_modules", ["q_proj", "k_proj", "v_proj", "o_proj"]
                    )
                ),
                "layers_to_transform": (
                    list(lora_cfg.get("layers_to_transform"))
                    if lora_cfg.get("layers_to_transform")
                    else None
                ),
            }
        elif mode in ("none", "disabled", ""):
            lora_block = {"mode": "none"}
        else:
            raise ValueError(
                f"export_run: unknown lora_cfg.export_mode={mode!r}; "
                "expected 'adapter_only' | 'hf_upload' | 'none'."
            )

    runtime_meta = {
        "run_id": result.run_id,
        "model_name": result.model_name,
        # Tag the shipped runtime architecture so future debug sessions can
        # tell at a glance which inference plumbing this bundle uses.
        # ``streamed_flush_v1``: opportunistic per-call mini-batches inside
        # ``acquisition_function`` (no big flush inside the first
        # ``predict()``), HF_HUB_OFFLINE forced at module import to satisfy
        # PAIEC-NETWORK-001, no encoder eviction (both 4 B models stay
        # co-resident on L4 for the entire round).
        "runtime_architecture": "streamed_flush_v1",
        "encoder_model_id": (
            lora_runtime_id_override or encoder_cfg["model_id"]
        ),
        # The encoder side may have promoted max_length from config-null to a
        # data-driven cap. We persist the *effective* number so the runtime
        # tokenizes consistently with the offline cache.
        "max_length": int(encoder_cfg.get("max_length") or 512),
        # Per-batch size used by the runtime's ``_embed_batch`` path.
        # Default 16 (proven-safe on a 24 GB L4 with Qwen3-Embedding-4B
        # bf16 co-resident with Qwen3-4B-Instruct -- bs=32 has OOM'd in
        # the wild). The encoder no longer gets evicted before the judge
        # phase under the streamed-flush architecture, so the safe
        # ceiling is the *co-resident* number.
        "encoder_runtime_batch_size": int(
            encoder_cfg.get(
                "runtime_batch_size",
                16
                if int(encoder_cfg.get("batch_size", 16) or 16) > 64
                else encoder_cfg.get("batch_size", 16),
            )
        ),
        "pooling": encoder_cfg.get("pooling", "mean"),
        "use_contextual_item_text": bool(
            encoder_cfg.get("use_contextual_item_text", True)
        ),
        "query_prefix": encoder_cfg.get("query_prefix", ""),
        "passage_prefix": encoder_cfg.get("passage_prefix", ""),
        "qwen3_instruction": encoder_cfg.get("qwen3_instruction", ""),
        "default_prob": 0.5,
        "default_calibrator": dict(default_calibrator or {"kind": "identity"}),
        "best_val_log_loss": float(result.best_val_log_loss),
        "best_val_brier": float(result.best_val_brier),
        "best_val_auc": result.best_val_auc,
        "k": int(result.k),
        "epoch_best": int(result.epoch_best),
        "pool_feature_names": list(pool_feature_names) if pool_feature_names else [
            "token_len",
            "char_len",
            "has_latex",
            "has_code",
            "n_questions",
            "n_numbers",
            "is_multiple_choice",
            "n_choices",
            "lang_en",
        ],
        "judge": judge_block,
        "nn_features": {
            # ``enabled`` reflects the checkpoint's verdict so the runtime
            # cannot diverge from the trained head's expectations.
            "enabled": bool(ckpt_uses_nn),
            "k": int((nn_features_cfg or {}).get("k", 16)),
            "runtime_k": int(
                (nn_features_cfg or {}).get(
                    "runtime_k", (nn_features_cfg or {}).get("k", 16)
                )
            ),
            "similarity": str(
                (nn_features_cfg or {}).get("similarity", "cosine")
            ),
            "feature_dim": int(
                (nn_features_cfg or {}).get(
                    "feature_dim", ckpt_nn_feature_dim or 8
                )
            ),
            "fallback_value": float(
                (nn_features_cfg or {}).get("fallback_value", 0.0)
            ),
            "top1_missing_sentinel": float(
                (nn_features_cfg or {}).get("top1_missing_sentinel", -1.0)
            ),
        },
    }
    if lora_block is not None:
        runtime_meta["lora"] = lora_block
    (artifacts / "runtime_meta.json").write_text(
        json.dumps(runtime_meta, indent=2, default=str)
    )

    (sub / "model.py").write_text(_RUNTIME_MODEL_PY, encoding="utf-8")
    if include_labeling:
        (sub / "labeling.py").write_text(_RUNTIME_LABELING_PY, encoding="utf-8")

    # models.txt: encoder first, then (optionally) the judge so the platform
    # pre-fetches both. ``hf_upload`` LoRA mode overrides the encoder id
    # with the merged-encoder repo. Caller-provided extras come last and are
    # deduped.
    declared = [lora_runtime_id_override or encoder_cfg["model_id"]]
    for m in lora_extra_models:
        if m and m not in declared:
            declared.append(m)
    if (
        judge_block["enabled"]
        and judge_block["ship_at_runtime"]
        and judge_block["model_id"]
        and judge_block["model_id"] not in declared
    ):
        declared.append(judge_block["model_id"])
    if extra_models_txt:
        for m in extra_models_txt:
            if m and m not in declared:
                declared.append(m)
    (sub / "models.txt").write_text("\n".join(declared) + "\n", encoding="utf-8")

    # ``requirements.txt`` is OPTIONAL on Codabench. The working slim
    # bundle did not ship one and ran cleanly; every recent bundle that
    # included one (with the optional ``faiss-cpu`` line) failed
    # PAIEC-UNKNOWN-001. The platform pre-installs torch, numpy,
    # transformers, safetensors, tokenizers, etc., so we only ship a
    # requirements.txt when the caller explicitly opts in OR when the
    # LoRA adapter export mode actually needs ``peft``.
    needs_lora_reqs = bool(lora_requirements_addendum.strip())
    if ship_requirements_txt or needs_lora_reqs:
        (sub / "requirements.txt").write_text(
            _RUNTIME_REQUIREMENTS + lora_requirements_addendum, encoding="utf-8"
        )
    else:
        LOG.info(
            "Skipping requirements.txt (ship_requirements_txt=False, "
            "no LoRA requirements). Codabench will use its pre-installed "
            "torch / transformers / numpy stack."
        )

    LOG.info(
        "Wrote submission to %s (declared models: %s)", sub.resolve(), declared
    )
    return sub


def bundle_training_cache(
    *,
    items_parquet_path: str | os.PathLike[str],
    out_dir: str | os.PathLike[str],
    submission_cache_cfg: Mapping,
    encoder_cfg: Mapping,
    items_meta_df=None,
    cluster_assignments=None,
    n_clusters: int = 0,
    train_df=None,
    nn_features_cfg: Mapping | None = None,
    subject_to_id: Mapping[str, int] | None = None,
) -> CacheExportResult:
    """Build the int8 / PCA / FAISS training-item cache.

    Thin wrapper around ``src.cache_export.export_item_cache`` that pulls
    arguments from the config blocks the notebook already has at hand.

    Raises RuntimeError if ``submission_cache_cfg.max_bundle_size_mb`` is
    exceeded so the notebook can fail loudly before zip time.

    When ``nn_features_cfg`` and ``subject_to_id`` are provided, the
    submission cache additionally ships the per-(subject, item) pass-rate
    sparse matrix, the matching observation mask, the explicit subject
    indexer mapping, and the locked NN feature schema -- everything the
    runtime needs to compute the same 8-scalar NN feature vector it was
    trained on. The asymmetric two-cache design (full-fidelity training
    index vs. compressed runtime index) is intentional; see ``src.nn_features``.
    """
    runtime_k = int(submission_cache_cfg.get("runtime_k", 16))
    if nn_features_cfg is not None:
        runtime_k = int(
            submission_cache_cfg.get(
                "runtime_k", int(nn_features_cfg.get("k", runtime_k))
            )
        )
    cfg = CacheExportConfig(
        enabled=bool(submission_cache_cfg.get("enabled", True)),
        quantize=str(submission_cache_cfg.get("quantize", "int8")),
        pca_dim=submission_cache_cfg.get("pca_dim"),
        include_faiss_index=bool(
            submission_cache_cfg.get(
                "include_top_k_index",
                submission_cache_cfg.get("include_faiss_index", True),
            )
        ),
        faiss_index_type=str(submission_cache_cfg.get("faiss_index_type", "HNSW32")),
        max_bundle_size_mb=float(submission_cache_cfg.get("max_bundle_size_mb", 200)),
        passrate_format=str(submission_cache_cfg.get("passrate_format", "cluster")),
        encoder_id=str(encoder_cfg.get("model_id", "")),
        query_prefix=str(encoder_cfg.get("query_prefix", "")),
        passage_prefix=str(encoder_cfg.get("passage_prefix", "")),
        runtime_k=runtime_k,
    )
    # Build a copy of the nn config with runtime_k injected so the runtime
    # can verify which K it should use at test time (may be smaller than
    # the training-time K when bundle size is tight).
    nn_cfg_for_export = None
    if nn_features_cfg is not None:
        nn_cfg_for_export = dict(nn_features_cfg)
        nn_cfg_for_export.setdefault("runtime_k", runtime_k)
    result = export_item_cache(
        items_parquet_path=Path(items_parquet_path),
        out_dir=Path(out_dir),
        cfg=cfg,
        items_meta_df=items_meta_df,
        cluster_assignments=cluster_assignments,
        n_clusters=int(n_clusters),
        train_df=train_df,
        nn_features_cfg=nn_cfg_for_export,
        subject_to_id=subject_to_id,
    )
    if result.failed:
        raise RuntimeError(result.error or "submission cache export failed")
    return result


def make_submission_zip(
    submission_dir: str | os.PathLike[str] = "submission",
    zip_path: str | os.PathLike[str] = "submission.zip",
    *,
    max_zip_size_mb: float | None = 70.0,
) -> Path:
    """Zip the submission folder. Returns the zip path.

    ``max_zip_size_mb`` is a hard cap on the size of the resulting ZIP
    (the file the user uploads to Codabench). If the produced ZIP would
    exceed this, we delete it and raise -- silently shipping a 400 MB
    bundle has burned us before. Pass ``None`` to disable the check.

    Entry names are written with POSIX-style forward slashes so a Linux
    ``unzip`` on the platform extracts them into the expected directory
    layout (Windows' default writer would otherwise embed backslashes).
    """
    sub = Path(submission_dir)
    zip_path = Path(zip_path)
    if zip_path.exists():
        zip_path.unlink()
    with zipfile.ZipFile(
        zip_path, "w", compression=zipfile.ZIP_DEFLATED, compresslevel=9
    ) as zf:
        for path in sub.rglob("*"):
            if path.is_file():
                arc = path.relative_to(sub).as_posix()
                zf.write(path, arcname=arc)
    size_mb = zip_path.stat().st_size / (1024 * 1024)
    LOG.info("Wrote %s  (%.2f MB)", zip_path.resolve(), size_mb)
    if max_zip_size_mb is not None and size_mb > float(max_zip_size_mb):
        zip_path.unlink(missing_ok=True)
        raise RuntimeError(
            f"submission zip is {size_mb:.2f} MB, exceeds "
            f"max_zip_size_mb={float(max_zip_size_mb):.0f} MB. "
            "Drop the unused training cache, lower submission_cache.pca_dim, "
            "or raise the cap explicitly in configs/default.yaml -> "
            "submission.max_zip_size_mb."
        )
    return zip_path


