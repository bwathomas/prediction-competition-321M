class _ItemParameterMap(nn.Module):
    def __init__(self, item_embed_dim: int, k: int, hidden: int, dropout: float = 0.1):
        super().__init__()
        self.norm = nn.LayerNorm(item_embed_dim)
        self.fc1 = nn.Linear(item_embed_dim, hidden)
        self.drop = nn.Dropout(dropout)
        self.head_factor = nn.Linear(hidden, k)
        self.head_diff = nn.Linear(hidden, 1)

    def forward(self, x: torch.Tensor):
        h = F.silu(self.fc1(self.norm(x)))
        h = self.drop(h)
        return self.head_factor(h), self.head_diff(h).squeeze(-1)


class _ItemIRTHeads(nn.Module):
    def __init__(self, item_dim: int, hidden: int, dropout: float = 0.0):
        super().__init__()
        self.beta_head = nn.Sequential(
            nn.LayerNorm(item_dim),
            nn.Linear(item_dim, hidden),
            nn.GELU(),
            nn.Dropout(dropout),
            nn.Linear(hidden, 1),
        )
        self.alpha_head = nn.Sequential(
            nn.LayerNorm(item_dim),
            nn.Linear(item_dim, hidden),
            nn.GELU(),
            nn.Dropout(dropout),
            nn.Linear(hidden, 1),
        )
        self._alpha_pre_bias = 0.54

    def forward(self, ie):
        beta = self.beta_head(ie).squeeze(-1)
        alpha_pre = self.alpha_head(ie).squeeze(-1) + self._alpha_pre_bias
        return beta, F.softplus(alpha_pre)


def _cluster_emb_runtime(cfg, cluster_embedding, cluster_ids):
    if cluster_embedding is None or cluster_ids is None:
        return None
    if cluster_ids.numel() == 0 or cluster_ids.dim() < 1:
        return None
    return cluster_embedding(cluster_ids.long())


class _KFactorBase(nn.Module):
    def __init__(self, cfg: dict):
        super().__init__()
        self.cfg = cfg
        self.mu = nn.Parameter(torch.zeros(1))
        self.alpha = nn.Embedding(cfg["n_subjects"], 1)
        self.beta = nn.Embedding(cfg["n_benchmark_conditions"], 1)
        self.u = nn.Embedding(cfg["n_subjects"], cfg["k"])
        self.item_map = _ItemParameterMap(
            item_embed_dim=cfg["item_embed_dim"],
            k=cfg["k"],
            hidden=cfg["item_map_hidden_dim"],
            dropout=cfg.get("dropout", 0.0),
        )
        self.cluster_embedding = None
        if (
            cfg.get("use_cluster_features")
            and cfg.get("n_clusters", 0) > 0
            and cfg.get("cluster_embed_dim", 0) > 0
        ):
            self.cluster_embedding = nn.Embedding(
                cfg["n_clusters"] + 1,
                cfg["cluster_embed_dim"],
                padding_idx=0,
            )

    def _factor(self, s, bc, ie):
        u_s = self.u(s)
        alpha_s = self.alpha(s).squeeze(-1)
        beta_bc = self.beta(bc).squeeze(-1)
        v_i, d_i = self.item_map(ie)
        k = max(1, self.cfg["k"])
        interaction = (u_s * v_i).sum(dim=-1) / math.sqrt(k)
        eta = self.mu + alpha_s + beta_bc - d_i + interaction
        return eta, u_s, v_i, ie


class _KFactor(_KFactorBase):
    def forward(self, s, bc, ie, se=None, pool_feats=None, cluster_ids=None, judge_feats=None, nn_feats=None):
        eta, *_ = self._factor(s, bc, ie)
        return eta


def _residual_features(cfg, u_s, v_i, ie, beta_bc, se, pool_feats, cluster_emb, judge_feats, nn_feats):
    parts = [u_s, v_i, u_s * v_i, ie, beta_bc]
    if cfg.get("use_subject_text_embedding") and se is not None and se.shape[-1] > 0:
        parts.append(se)
    if cfg.get("use_pool_features") and pool_feats is not None and pool_feats.shape[-1] > 0:
        parts.append(pool_feats)
    if (
        cfg.get("use_cluster_features")
        and cluster_emb is not None
        and cluster_emb.shape[-1] > 0
    ):
        parts.append(cluster_emb)
    if (
        cfg.get("use_judge_features")
        and judge_feats is not None
        and judge_feats.shape[-1] > 0
    ):
        parts.append(judge_feats)
    if (
        cfg.get("use_nn_features")
        and nn_feats is not None
        and nn_feats.shape[-1] > 0
    ):
        parts.append(nn_feats)
    return torch.cat(parts, dim=-1)


def _residual_input_dim(cfg: dict) -> int:
    base = cfg["k"] * 3 + cfg["item_embed_dim"] + 1
    if cfg.get("use_subject_text_embedding"):
        base += int(cfg.get("subject_embed_dim", 0))
    if cfg.get("use_pool_features"):
        base += int(cfg.get("pool_feature_dim", 0))
    if cfg.get("use_cluster_features") and cfg.get("n_clusters", 0) > 0:
        base += int(cfg.get("cluster_embed_dim", 0))
    if cfg.get("use_judge_features"):
        base += int(cfg.get("judge_feature_dim", 0))
    if cfg.get("use_nn_features"):
        base += int(cfg.get("nn_feature_dim", 0))
    return base


