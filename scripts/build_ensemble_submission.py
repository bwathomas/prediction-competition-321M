# CLI
# ---------------------------------------------------------------------------


def _parse_args(argv: Sequence[str] | None = None) -> argparse.Namespace:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument(
        "--bundle",
        action="append",
        default=[],
        help="Path to a submission zip OR an already-extracted directory.  "
             "Repeat the flag for each submodel (the order matches --weights).",
    )
    ap.add_argument(
        "--weights",
        type=float,
        nargs="+",
        help="Ensemble weights, in the same order as --bundle.",
    )
    ap.add_argument(
        "--name",
        action="append",
        default=[],
        help="Optional submodel directory names; defaults to bundle stem.",
    )
    ap.add_argument(
        "--combine",
        default="logit",
        choices=["prob", "logit"],
        help="Combine space.  'logit' (default) is weighted sum of logits "
             "passed through sigmoid; 'prob' is a plain weighted average.",
    )
    ap.add_argument("--intercept", type=float, default=0.0)
    ap.add_argument("--default-prob", type=float, default=0.5)
    ap.add_argument("--config", type=Path, default=None,
                    help="Path to a JSON config (matches ensemble_meta.json) "
                         "to use instead of CLI flags.")
    ap.add_argument("--out", required=False, type=Path, default=Path("ensemble_submission.zip"))
    ap.add_argument("--workspace", type=Path, default=None,
                    help="Optional staging directory (default: a fresh tempdir).")
    ap.add_argument("-v", "--verbose", action="count", default=0)
    return ap.parse_args(argv)


def main(argv: Sequence[str] | None = None) -> int:
    args = _parse_args(argv)
    logging.basicConfig(
        level=logging.DEBUG if args.verbose >= 2 else (
            logging.INFO if args.verbose >= 1 else logging.WARNING
        ),
        format="[%(asctime)s] %(name)s %(levelname)s: %(message)s",
        datefmt="%H:%M:%S",
    )
    if args.config is not None:
        cfg = json.loads(Path(args.config).read_text(encoding="utf-8"))
        bundles = cfg["bundles"]
        weights = cfg["weights"]
        names = cfg.get("submodel_names")
        combine_space = cfg.get("combine_space", args.combine)
        intercept = cfg.get("intercept", args.intercept)
        default_prob = cfg.get("default_prob", args.default_prob)
        notes = cfg.get("notes")
    else:
        if not args.bundle or not args.weights:
            raise SystemExit("--bundle and --weights are required (or use --config)")
        bundles = args.bundle
        weights = args.weights
        names = args.name if args.name else None
        combine_space = args.combine
        intercept = args.intercept
        default_prob = args.default_prob
        notes = None
    out = build_ensemble(
        bundles=bundles,
        weights=weights,
        out_zip=args.out,
        submodel_names=names,
        combine_space=combine_space,
        intercept=intercept,
        default_prob=default_prob,
        workspace_dir=args.workspace,
        extra_notes=notes,
    )
    print(f"wrote {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
