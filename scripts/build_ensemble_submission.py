"""Build a Codabench ensemble submission from a list of bundles + weights.

Given:

    - one or more extracted submission bundles (each with model.py,
      labeling.py, artifacts/, ...)
    - a vector of ensemble weights
    - a combination space ("prob" or "logit") and optional intercept

this script produces a self-contained ZIP that the Codabench runner can
ingest directly.  Output layout:

    ensemble.zip/
      model.py                     # ensemble dispatcher (see below)
      labeling.py                  # ensemble acquisition_function
      models.txt                   # union of every submodel's HF repos
      ensemble_meta.json           # weights + per-submodel name list
      submodels/
        <submodel_name>/           # full copy of each chosen bundle
          model.py
          labeling.py
          artifacts/
            checkpoint.pt
            runtime_meta.json
            pool_features_stats.json
            ...
          ...

At Codabench runtime, the platform imports our ``model.py`` and
``labeling.py``.  ``model.py`` loads each submodel's ``model.py`` as a
uniquely-named module via ``importlib`` (so multiple submodules with the
same ``model`` name don't collide in ``sys.modules``).

``predict()`` calls every submodel's ``predict()`` and combines the
returned probabilities by the configured weights.  ``labeling.py`` drives
every submodel's ``_enqueue_for_batch`` (the streamed-flush hook) so the
encoder caches still warm up across the 256k acquisition calls.

USAGE
-----

    python scripts/build_ensemble_submission.py \\
        --bundle ensemble_bundles/dropout03_fwls_combined.zip \\
        --bundle ensemble_bundles/LGAI_fixed_v2.zip \\
        --bundle ensemble_bundles/nemotron_trc_v6.zip \\
        --weights 0.3 0.35 0.35 \\
        --combine logit \\
        --out ensemble_submission.zip

You can also pass a JSON config via --config to keep the call site clean
from the Colab notebook.  See ``ensemble_meta.json`` schema below.
"""

from __future__ import annotations

import argparse
import json
import logging
import os
import shutil
import sys
import tempfile
import zipfile
from pathlib import Path
from typing import Any, Sequence

LOG = logging.getLogger("build_ensemble")


# ---------------------------------------------------------------------------
# model.py template (ensemble dispatcher)
# ---------------------------------------------------------------------------
#
# We deliberately keep this small (<300 lines): every submodel ships its own
# encoder / IRT head / calibrator, so we only need to *call into* each
# submodel and combine the answers.  All the heavy work happens inside the
# submodels' own ``predict()`` implementations.

_ENSEMBLE_MODEL_PY = r'''"""Codabench runtime entry point -- ensemble dispatcher.

Auto-generated by scripts/build_ensemble_submission.py.  Do not edit.

Loads N submodels (each itself a full Codabench submission) and dispatches
``predict()`` to all of them, combining probabilities according to the
weights captured in ``ensemble_meta.json``.
"""

from __future__ import annotations

import importlib.util
import json
import logging
import math
import os
import sys
import time
import traceback
from pathlib import Path
from types import ModuleType

# Preserve HuggingFace offline mode from the platform; idempotent if the
# platform already set these.
os.environ.setdefault("HF_HUB_OFFLINE", "1")
os.environ.setdefault("TRANSFORMERS_OFFLINE", "1")
os.environ.setdefault("HF_DATASETS_OFFLINE", "1")

# Reduce CUDA allocator fragmentation -- critical when 5 LLM encoders share
# a single 80GB A100.  Must be set BEFORE the first torch import; idempotent.
_alloc_cfg = os.environ.get("PYTORCH_ALLOC_CONF", "")
if "expandable_segments" not in _alloc_cfg:
    _new = "expandable_segments:True"
    os.environ["PYTORCH_ALLOC_CONF"] = (_alloc_cfg + "," + _new).lstrip(",")
# PyTorch < 2.4 reads PYTORCH_CUDA_ALLOC_CONF instead; set both for safety.
_alloc_cfg = os.environ.get("PYTORCH_CUDA_ALLOC_CONF", "")
if "expandable_segments" not in _alloc_cfg:
    _new = "expandable_segments:True"
    os.environ["PYTORCH_CUDA_ALLOC_CONF"] = (_alloc_cfg + "," + _new).lstrip(",")

LOG = logging.getLogger("ensemble")

HERE = Path(__file__).resolve().parent
SUBMODELS_DIR = HERE / "submodels"
META_PATH = HERE / "ensemble_meta.json"

with open(META_PATH, "r", encoding="utf-8") as fh:
    ENSEMBLE_META: dict = json.load(fh)

SUBMODEL_NAMES: list[str] = list(ENSEMBLE_META["submodels"])
WEIGHTS: list[float] = [float(w) for w in ENSEMBLE_META["weights"]]
COMBINE_SPACE: str = str(ENSEMBLE_META.get("combine_space", "logit")).lower()
INTERCEPT: float = float(ENSEMBLE_META.get("intercept", 0.0))
DEFAULT_PROB: float = float(ENSEMBLE_META.get("default_prob", 0.5))
EPS: float = 1e-6

assert len(SUBMODEL_NAMES) == len(WEIGHTS), (
    f"ensemble_meta.json: |submodels|={len(SUBMODEL_NAMES)} but "
    f"|weights|={len(WEIGHTS)}"
)
if COMBINE_SPACE not in {"prob", "logit"}:
    raise ValueError(f"combine_space must be 'prob' or 'logit', got {COMBINE_SPACE!r}")


def _logit(p: float) -> float:
    p = min(max(p, EPS), 1.0 - EPS)
    return math.log(p / (1.0 - p))


def _sigmoid(x: float) -> float:
    if x >= 0:
        z = math.exp(-x)
        return 1.0 / (1.0 + z)
    z = math.exp(x)
    return z / (1.0 + z)


def _load_submodel(name: str) -> ModuleType:
    """Import a submodel's ``model.py`` as a uniquely-named module.

    We append the submodel's directory to ``sys.path`` *temporarily* so
    that any ``import labeling`` or ``import model`` lines inside the
    submodel still resolve, even though we load via a synthetic name.
    """
    sub_dir = SUBMODELS_DIR / name
    model_py = sub_dir / "model.py"
    if not model_py.is_file():
        raise FileNotFoundError(f"submodel {name!r}: missing model.py at {model_py}")
    mod_name = f"_ensemble_submodel_{name}"
    spec = importlib.util.spec_from_file_location(mod_name, model_py)
    if spec is None or spec.loader is None:
        raise ImportError(f"cannot build spec for {model_py}")
    module = importlib.util.module_from_spec(spec)
    # Register before exec so any internal imports that look up the module
    # in sys.modules succeed.
    sys.modules[mod_name] = module
    sub_dir_str = str(sub_dir)
    in_sys_path = sub_dir_str in sys.path
    if not in_sys_path:
        sys.path.insert(0, sub_dir_str)
    try:
        t0 = time.time()
        LOG.info("loading submodel %s ...", name)
        spec.loader.exec_module(module)
        LOG.info("  loaded %s in %.1fs", name, time.time() - t0)
    finally:
        if not in_sys_path:
            try:
                sys.path.remove(sub_dir_str)
            except ValueError:
                pass
    if not hasattr(module, "predict"):
        raise AttributeError(f"submodel {name!r}: model.py has no predict()")
    return module


# ---------------------------------------------------------------------------
# Load every submodel ONCE at module scope.  This is the expensive step
# (HuggingFace weight load, tokenizer load, calibrator load) and matches
# the platform's expectation that container init does all heavy setup.
# ---------------------------------------------------------------------------

_SUBMODELS: list[ModuleType] = []
_SUBMODEL_LOAD_ERRORS: dict[str, str] = {}
for _name in SUBMODEL_NAMES:
    try:
        _SUBMODELS.append(_load_submodel(_name))
    except Exception as e:  # noqa: BLE001
        # Capture but do not crash the container -- a missing submodel
        # should not break the whole ensemble.  We will just skip it at
        # predict() time and re-normalize weights over the survivors.
        LOG.exception("FAILED to load submodel %s", _name)
        _SUBMODELS.append(None)  # type: ignore[arg-type]
        _SUBMODEL_LOAD_ERRORS[_name] = f"{type(e).__name__}: {e}"

# Expose for labeling.py
SUBMODELS = _SUBMODELS  # alias
SUBMODEL_NAMES_LOADED = [
    n for n, m in zip(SUBMODEL_NAMES, _SUBMODELS) if m is not None
]
LOG.info(
    "ensemble: loaded %d/%d submodels (errors: %s)",
    len(SUBMODEL_NAMES_LOADED),
    len(SUBMODEL_NAMES),
    _SUBMODEL_LOAD_ERRORS,
)


def predict(input: dict, labeled=None) -> float:  # noqa: A002
    """Combine per-submodel ``predict()`` returns via configured weights.

    Failure handling: any submodel that raises or returns NaN is excluded
    for this call and the remaining weights are renormalized.  If all
    submodels fail we fall back to ``DEFAULT_PROB``.
    """
    probs: list[float] = []
    eff_weights: list[float] = []
    for name, sub, w in zip(SUBMODEL_NAMES, _SUBMODELS, WEIGHTS):
        if sub is None:
            continue
        try:
            p = sub.predict(input, labeled)
            pf = float(p)
        except Exception as e:  # noqa: BLE001
            LOG.warning("predict(%s) raised: %s", name, e)
            continue
        if not math.isfinite(pf):
            continue
        probs.append(min(max(pf, EPS), 1.0 - EPS))
        eff_weights.append(float(w))
    if not probs:
        return float(DEFAULT_PROB)
    w_sum = sum(eff_weights)
    if not math.isfinite(w_sum) or w_sum <= 0:
        eff_weights = [1.0 / len(probs)] * len(probs)
        w_sum = 1.0
    if COMBINE_SPACE == "prob":
        ens = sum(w * p for w, p in zip(eff_weights, probs)) / w_sum
        ens = min(max(ens, EPS), 1.0 - EPS)
        return float(ens)
    # logit space
    z = INTERCEPT + sum(w * _logit(p) for w, p in zip(eff_weights, probs))
    # Optional: when weights live on a simplex we keep z = sum(w * logit(p))
    # which is a convex combination of logits, NOT divided by w_sum
    # (the user can always pass unscaled weights and we use them as-is).
    return float(_sigmoid(z))


# Optional debugging hook -- the harness ignores anything outside predict().
def __ensemble_debug_state() -> dict:
    return {
        "submodels": SUBMODEL_NAMES,
        "loaded": SUBMODEL_NAMES_LOADED,
        "load_errors": _SUBMODEL_LOAD_ERRORS,
        "weights": WEIGHTS,
        "combine_space": COMBINE_SPACE,
        "intercept": INTERCEPT,
    }
'''


# ---------------------------------------------------------------------------
# labeling.py template (ensemble acquisition function)
# ---------------------------------------------------------------------------
#
# Strategy:
#   1. Side-channel: call EVERY submodel's `_enqueue_for_batch` if present
#      so each submodel's streamed-flush queue gets fed.  This keeps the
#      per-call cost amortized across the ~256k acquisition calls instead
#      of all hitting the first predict().
#   2. Scoring: re-use the first submodel's `acquisition_function` if
#      available (its dual-pool stratification logic is well-tested).  If
#      it raises or is missing, fall back to a simple new-bc-vs-known-bc
#      score using the first submodel's `_BC_TO_ID`.
#
# Because we don't ship the submodel's own labeling.py modules (they each
# import `from model import ...` which would refer to the WRONG module
# inside the ensemble), we re-implement the dispatch here.

_ENSEMBLE_LABELING_PY = r'''"""Codabench runtime acquisition function -- ensemble dispatcher.

Auto-generated by scripts/build_ensemble_submission.py.  Do not edit.

Calls every submodel's ``_enqueue_for_batch`` (if present) so each
submodel can warm its encoder cache during the acquisition pass, then
returns a single acquisition score using the first submodel's known
labeling logic (dual-pool stratification).
"""

from __future__ import annotations

import hashlib
import logging
import math
import os

try:
    from model import SUBMODELS, SUBMODEL_NAMES, SUBMODEL_NAMES_LOADED  # type: ignore
except Exception:  # noqa: BLE001
    SUBMODELS = []  # type: ignore
    SUBMODEL_NAMES = []  # type: ignore
    SUBMODEL_NAMES_LOADED = []  # type: ignore

LOG = logging.getLogger("ensemble.labeling")

_FRACTION_NEW_POOL = 0.95

# How many distinct OOM warnings to emit per submodel before going silent.
# (When 5 big encoders share 80GB the warning spam is enormous and hides
# the actual signal in the logs.)
_OOM_LOG_LIMIT = int(os.environ.get("ENSEMBLE_OOM_LOG_LIMIT", "3"))
_OOM_COUNTS: dict[str, int] = {}


def _is_oom(exc: BaseException) -> bool:
    msg = str(exc)
    return "out of memory" in msg.lower() or "OutOfMemory" in msg


def _maybe_recover_oom() -> None:
    """Free unused CUDA cache so the next enqueue has a fighting chance.

    Cheap (microseconds) when there's nothing to free; expensive only after
    a real OOM.  We deliberately do NOT call this on every enqueue -- only
    after one already raised, since the happy-path cost would dominate.
    """
    try:
        import torch  # imported here to keep labeling.py importable without torch

        if torch.cuda.is_available():
            torch.cuda.empty_cache()
    except Exception:  # noqa: BLE001
        pass


def _item_in_new_pool(item_content: str) -> bool:
    h = hashlib.blake2b(item_content.encode("utf-8"), digest_size=8).digest()
    n = int.from_bytes(h, "little")
    return (n / float(2 ** 64)) < _FRACTION_NEW_POOL


def _stable_tiebreak(*parts: str) -> float:
    h = hashlib.blake2b(("\x00".join(parts)).encode("utf-8"), digest_size=8).digest()
    n = int.from_bytes(h, "little")
    return (n / 2 ** 64) - 0.5


def _enqueue_into_all(input: dict) -> None:  # noqa: A002
    """Side-channel: stream batches into every submodel's pending queues.

    OOMs are caught per-submodel, logged only ``_OOM_LOG_LIMIT`` times each,
    and trigger a ``torch.cuda.empty_cache()`` so the next submodel in the
    iteration may succeed.  This keeps the acquisition phase healthy even
    when memory headroom is tight.
    """
    benchmark = str(input.get("benchmark", "") or "")
    condition = str(input.get("condition", "none") or "none")
    subject_content = str(input.get("subject_content", "") or "")
    item_content = str(input.get("item_content", "") or "")
    for name, sub in zip(SUBMODEL_NAMES, SUBMODELS):
        if sub is None:
            continue
        enq = getattr(sub, "_enqueue_for_batch", None)
        if enq is None:
            continue
        try:
            enq(
                benchmark=benchmark,
                condition=condition,
                subject_content=subject_content,
                item_content=item_content,
            )
        except Exception as e:  # noqa: BLE001
            oom = _is_oom(e)
            seen = _OOM_COUNTS.get(name, 0)
            if seen < _OOM_LOG_LIMIT:
                _OOM_COUNTS[name] = seen + 1
                LOG.warning(
                    "enqueue(%s) raised%s: %s",
                    name,
                    " [OOM]" if oom else "",
                    str(e).splitlines()[0] if str(e) else type(e).__name__,
                )
                if seen + 1 == _OOM_LOG_LIMIT:
                    LOG.warning(
                        "enqueue(%s): further errors will be silenced "
                        "(_OOM_LOG_LIMIT=%d)",
                        name,
                        _OOM_LOG_LIMIT,
                    )
            if oom:
                _maybe_recover_oom()


def acquisition_function(input: dict) -> float:  # noqa: A002
    _enqueue_into_all(input)

    # Pick the first loaded submodel that exposes the bookkeeping we need.
    scorer = None
    for sub in SUBMODELS:
        if sub is None:
            continue
        if (
            hasattr(sub, "_BC_TO_ID")
            and hasattr(sub, "normalize_condition")
            and hasattr(sub, "stable_sha256")
        ):
            scorer = sub
            break
    if scorer is None:
        return 0.0

    try:
        benchmark = str(input.get("benchmark", "") or "")
        condition_raw = str(input.get("condition", "none") or "none")
        subject_content = str(input.get("subject_content", "") or "")
        item_content = str(input.get("item_content", "") or "")

        condition = scorer.normalize_condition(condition_raw)
        bc_key = "{0}::{1}".format(benchmark, condition)
        bc_id = int(getattr(scorer, "_BC_TO_ID").get(bc_key, 0))

        # Graded-mode anchoring when train counts are present; binary fallback
        # otherwise -- mirrors the submodel's own labeling.py logic.
        n_train_per_bc = getattr(scorer, "_N_TRAIN_PER_BC", None)
        n_train_per_subject = getattr(scorer, "_N_TRAIN_PER_SUBJECT", None)
        subject_key = scorer.stable_sha256(subject_content)

        if isinstance(n_train_per_bc, dict) and isinstance(n_train_per_subject, dict):
            try:
                max_n_subj = (
                    max(n_train_per_subject.values()) if n_train_per_subject else 0
                )
                log_max = math.log1p(float(max_n_subj))
            except Exception:  # noqa: BLE001
                log_max = 0.0
            n_train_bc = float(n_train_per_bc.get(bc_key, 0))
            is_new_bc = (n_train_bc <= 0.0)
            n_sub = float(n_train_per_subject.get(subject_key, 0))
            anchoring = math.log1p(n_sub) / log_max if log_max > 0.0 else 0.0
        else:
            s_id = int(getattr(scorer, "_SUBJECT_TO_ID", {}).get(subject_key, 0))
            is_new_bc = (bc_id == 0)
            anchoring = 1.0 if s_id != 0 else 0.0

        in_new_pool = _item_in_new_pool(item_content)
        eligible = (in_new_pool == is_new_bc)
        bc_bonus = 1000.0 if eligible else 0.0
        tb = _stable_tiebreak(benchmark, condition, subject_content, item_content)
        return bc_bonus + 10.0 * anchoring + tb
    except Exception:  # noqa: BLE001
        return 0.0
'''


