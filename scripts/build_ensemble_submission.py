# Builder logic
# ---------------------------------------------------------------------------


def _safe_name(s: str) -> str:
    """Filesystem-safe submodel directory name (also valid as a Python ident).

    Drops dots so the synthetic module name ``_ensemble_submodel_<name>``
    parses correctly via ``importlib.util.spec_from_file_location``.
    """
    keep = "abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789_-"
    out = "".join(c if c in keep else "_" for c in s)
    # Avoid empty / numeric-leading names
    if not out or out[0].isdigit():
        out = "m_" + out
    return out


def _copy_bundle_into(src_dir: Path, dst_dir: Path) -> None:
    """Copy every file from ``src_dir`` into ``dst_dir`` (recursive)."""
    if dst_dir.exists():
        shutil.rmtree(dst_dir)
    shutil.copytree(src_dir, dst_dir)


def _stage_zip_into(src_zip: Path, dst_dir: Path) -> None:
    """Extract ``src_zip`` into ``dst_dir`` (a clean directory)."""
    if dst_dir.exists():
        shutil.rmtree(dst_dir)
    dst_dir.mkdir(parents=True, exist_ok=True)
    with zipfile.ZipFile(src_zip, "r") as zf:
        zf.extractall(dst_dir)
    # Normalise any backslash-in-name entries (created by Windows zippers).
    for p in list(dst_dir.rglob("*")):
        if "\\" in p.name:
            rel = p.relative_to(dst_dir).as_posix().replace("\\", "/")
            tgt = dst_dir / rel
            tgt.parent.mkdir(parents=True, exist_ok=True)
            try:
                p.replace(tgt)
            except Exception:  # noqa: BLE001
                pass


def _collect_models_txt_entries(submodels_dir: Path) -> list[str]:
    """Aggregate every submodel's models.txt entries; dedupe + preserve order."""
    seen: set[str] = set()
    out: list[str] = []
    for sub in sorted(submodels_dir.iterdir()):
        if not sub.is_dir():
            continue
        mt = sub / "models.txt"
        if not mt.exists():
            continue
        for line in mt.read_text(encoding="utf-8").splitlines():
            line = line.strip()
            if not line or line.startswith("#"):
                continue
            if line not in seen:
                seen.add(line)
                out.append(line)
    return out


def build_ensemble(
    bundles: Sequence[str | Path],
    weights: Sequence[float],
    out_zip: str | Path,
    *,
    submodel_names: Sequence[str] | None = None,
    combine_space: str = "logit",
    intercept: float = 0.0,
    default_prob: float = 0.5,
    workspace_dir: str | Path | None = None,
    extra_notes: dict[str, Any] | None = None,
) -> Path:
    """Build the ensemble submission zip.

    Parameters
    ----------
    bundles : sequence of paths to either (a) an extracted submission dir
        containing ``model.py`` or (b) a zipped submission bundle.
    weights : matching-length sequence of floats.  In ``prob`` space they
        should sum to 1; in ``logit`` space they're scaling factors on
        each model's logit.
    out_zip : path to write the output zip file to.
    submodel_names : optional human-readable name per submodel; defaults
        to the bundle filename stem.  Used as the directory name under
        ``submodels/``.
    combine_space : ``"prob"`` (simple weighted average) or ``"logit"``
        (weighted sum of logits + intercept, then sigmoid).
    intercept : only used when ``combine_space="logit"``.
    default_prob : returned by ``predict()`` if every submodel fails.
    workspace_dir : where to assemble the staged layout before zipping;
        a unique temp dir if not provided.
    extra_notes : free-form dict stored in ``ensemble_meta.json``.
    """
    if len(weights) != len(bundles):
        raise ValueError(
            f"|weights|={len(weights)} != |bundles|={len(bundles)}"
        )
    bundles = [Path(p) for p in bundles]
    if submodel_names is None:
        submodel_names = [
            _safe_name(p.stem if p.is_file() else p.name) for p in bundles
        ]
    submodel_names = [_safe_name(n) for n in submodel_names]
    if len(set(submodel_names)) != len(submodel_names):
        raise ValueError(f"submodel_names must be unique; got {submodel_names!r}")
    if combine_space not in {"prob", "logit"}:
        raise ValueError(f"combine_space must be 'prob' or 'logit'; got {combine_space!r}")

    if workspace_dir is None:
        workspace_dir = Path(tempfile.mkdtemp(prefix="ensemble_build_"))
    workspace_dir = Path(workspace_dir).resolve()
    workspace_dir.mkdir(parents=True, exist_ok=True)
    LOG.info("staging in %s", workspace_dir)

    out_dir = workspace_dir / "stage"
    if out_dir.exists():
        shutil.rmtree(out_dir)
    out_dir.mkdir(parents=True)
    submodels_dir = out_dir / "submodels"
    submodels_dir.mkdir()

    # 1. Stage every submodel
    for name, src in zip(submodel_names, bundles):
        dst = submodels_dir / name
        if src.is_dir():
            _copy_bundle_into(src, dst)
        elif src.is_file() and src.suffix.lower() == ".zip":
            _stage_zip_into(src, dst)
        else:
            raise FileNotFoundError(
                f"bundle {src!r} is neither a directory nor a .zip file"
            )
        if not (dst / "model.py").exists():
            raise RuntimeError(
                f"submodel {name!r}: model.py missing under {dst} after staging"
            )

    # 2. Write the ensemble dispatcher + labeling.py
    (out_dir / "model.py").write_text(_ENSEMBLE_MODEL_PY, encoding="utf-8")
    (out_dir / "labeling.py").write_text(_ENSEMBLE_LABELING_PY, encoding="utf-8")

    # 3. Aggregate models.txt (so the platform pre-fetches every encoder
    # the submodels need).  We dedupe + preserve order.
    models_lines = _collect_models_txt_entries(submodels_dir)
    if models_lines:
        if len(models_lines) > 5:
            LOG.warning(
                "models.txt has %d entries but the platform allows at most 5; "
                "the build will still proceed -- expect Codabench to reject this "
                "bundle if your team is on the strict-5 limit",
                len(models_lines),
            )
        (out_dir / "models.txt").write_text(
            "\n".join(models_lines) + "\n", encoding="utf-8"
        )

    # 4. ensemble_meta.json with weights and submodel list
    meta: dict[str, Any] = {
        "submodels": list(submodel_names),
        "weights": [float(w) for w in weights],
        "combine_space": combine_space,
        "intercept": float(intercept),
        "default_prob": float(default_prob),
        "models_txt_entries": models_lines,
    }
    if extra_notes:
        meta["notes"] = extra_notes
    (out_dir / "ensemble_meta.json").write_text(
        json.dumps(meta, indent=2), encoding="utf-8"
    )

    # 5. Smoke-check: every submodel has a model.py and at least one
    # artifact file; the dispatcher will import them at platform startup.
    for name in submodel_names:
        d = submodels_dir / name
        if not (d / "model.py").is_file():
            raise RuntimeError(f"smoke: submodel {name!r} missing model.py")

    # 6. Zip it
    out_zip = Path(out_zip).resolve()
    out_zip.parent.mkdir(parents=True, exist_ok=True)
    if out_zip.exists():
        out_zip.unlink()
    with zipfile.ZipFile(out_zip, "w", compression=zipfile.ZIP_DEFLATED) as zf:
        for p in out_dir.rglob("*"):
            if p.is_file():
                zf.write(p, p.relative_to(out_dir).as_posix())
    LOG.info("wrote %s (%.2f MB)", out_zip, out_zip.stat().st_size / 1e6)
    return out_zip


